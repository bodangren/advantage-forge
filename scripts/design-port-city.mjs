#!/usr/bin/env node
// Port city map: 14 x 12 tiles of 2 m (28 m x 24 m). Cell (c,r): x = -13+2c, z = -11+2r. +X east, -Z north.
// Townhouses in the north-west, lighthouse north-east, a cobble-quay basin in the south-east with piers and boats.
import { writeFileSync } from 'node:fs';
const X = (c) => -13 + 2 * c;
const Z = (r) => -11 + 2 * r;
const places = [];
const put = (asset, x, z, o = {}) => {
  const p = { asset, at: [x, o.y ?? 0, z] };
  if (o.yaw) p.yaw = o.yaw;
  if (o.scale) p.scale = o.scale;
  places.push(p);
};
const isWater = (c, r) => c >= 4 && c <= 11 && r >= 5;
const isQuay = (c, r) => !isWater(c, r) && ((r === 4 && c >= 3) || (c === 3 && r >= 5) || (c >= 12 && r >= 4));
const glyph = Array.from({ length: 12 }, () => Array(14).fill('.'));
for (let c = 0; c < 14; c++) for (let r = 0; r < 12; r++) {
  if (isWater(c, r)) { put('sea-water', X(c), Z(r)); glyph[r][c] = '~'; continue; }
  const q = isQuay(c, r);
  put(q ? 'cobble-floor' : 'desert-ground', X(c), Z(r));
  if (q) glyph[r][c] = '#';
}
// town row, north-west
put('townhouse', -11.5, -8.4); put('townhouse', -7.2, -8.6); put('townhouse', -2.8, -8.4);
put('farmhouse', -10.2, -3.6, { yaw: 0, scale: 0.8 });
put('cottage', -5.6, -4.2, { scale: 0.9 });
put('barn', 1.4, -5.2); // warehouse
put('lighthouse', 6.4, -8.2); // focal
put('merchant-ship', 10.6, -4.4, { yaw: 90 });
put('shop-stall', -9.6, 4.6, { yaw: 90 }); put('market-tent', -11.0, 7.6, { yaw: 90 }); put('market-tent', -11.0, 1.6, { yaw: 90 });
put('market-cart', -7.6, 2.0, { yaw: 90 }); put('handcart', -8.4, 6.8, { yaw: 60 });
// piers and boats
put('pier', -1.0, 1.0); put('pier', 3.0, 1.2); put('dock', 5.8, 5.0, { yaw: 90 }); put('dock', 0.4, 6.4, { yaw: 90 });
put('rowboat', 1.0, 3.4, { yaw: 100 }); put('rowboat', 5.4, 8.4, { yaw: 30 }); put('fishing-boat', -1.6, 8.4, { yaw: 80 });
put('longship', 8.0, 2.6, { yaw: 90 });
// props
const P = [
 ['barrel',-8.6,-1.6],['barrel',-8.0,-1.2],['crate',-5.6,-1.6],['crate',-5.0,-1.4],['sack',-4.4,-1.8],['barrel',-3.0,-1.8],['crate',-1.6,-2.2],['sack',-0.8,-2.0],
 ['barrel',2.2,-2.2],['barrel',2.8,-2.0],['crate',4.6,-2.2],['rope-coil',5.8,-2.2],['sack',7.6,-1.8],['crate',8.4,-2.2],['barrel',9.6,0.0],['crate',10.2,1.2],
 ['fishing-net',-7.0,3.0],['fishing-net',-7.0,5.6],['barrel',-7.0,8.0],['crate',-7.0,9.2],['sack',-7.2,6.6],['barrel',-9.0,9.4],['crate',-8.2,9.6],
 ['crate',11.4,3.4],['barrel',11.8,5.4],['sack',11.2,7.2],['crate',11.8,9.0],['barrel',11.2,10.2],['rope-coil',4.0,-2.2],
 ['hay-bale',-12.2,-1.0],['hay-bale',-12.2,10.4],['bush',-9.0,-6.0],['bush',-1.0,-5.6],['bush',3.8,-5.0],['bush',-12.2,4.0],['bush',12.2,-9.6],['bush',-0.6,-10.6],
 ['palm-tree',-12.4,1.0],['palm-tree',4.2,-3.6],['palm-tree',-4.8,-3.2],
 ['crate',0.2,1.0,0.55],['barrel',-1.4,1.2,0.55],['rope-coil',3.0,0.6,0.55],['sack',3.4,1.8,0.55],['crate',5.8,5.0,0.55],
];
for (const [a,x,z,y] of P) put(a, x, z, { y: y ?? 0, yaw: Math.round((x * 37 + z * 11) % 90) });
for (const [x,z] of [[-5.6,-2.4],[-2.2,-2.6],[1.4,-2.6],[6.6,-2.6],[10.6,-1.2],[11.6,4.6],[11.6,8.6],[-6.6,4.6],[-6.6,9.6],[-8.4,-2.6]]) put('lantern', x, z);
put('sailor',-7.0,0.4,{yaw:90}); put('sailor',-1.0,2.4,{yaw:200,y:0.55}); put('sailor',8.6,-0.4,{yaw:180}); put('sailor',11.4,6.2,{yaw:270});
put('sailor',-7.0,-2.4,{yaw:20}); put('sailor',2.4,-2.6,{yaw:160});
put('signpost',-4.0,-2.6,{yaw:160}); put('bench',-12.0,-5.6,{yaw:90}); put('bench',0.0,-3.4);
put('well',-8.0,-0.4);
const num = (v) => (Number.isInteger(v) ? String(v) : v.toFixed(2).replace(/0+$/, '').replace(/\.$/, ''));
const fmt = (p) => `  { asset: '${p.asset}', at: [${num(p.at[0])}, ${num(p.at[1])}, ${num(p.at[2])}]${p.yaw ? `, yaw: ${p.yaw}` : ''}${p.scale ? `, scale: ${p.scale}` : ''} },`;
writeFileSync('scenes/maps/port-city.ts', `// GENERATED by scripts/design-port-city.mjs — edit the generator, not this file.
import type { Place } from '../chibi-quest.js';
export function places(): Place[] {
  return [
${places.map(fmt).join('\n')}
  ];
}
`);
const tally = {};
for (const p of places) tally[p.asset] = (tally[p.asset] ?? 0) + 1;
writeFileSync('docs/map-mockups/port-city.md', `# Port city map (generated)

GENERATED by scripts/design-port-city.mjs. 14 x 12 tiles of 2 m (28 m x 24 m). Cell (c,r): x=-13+2c, z=-11+2r.

\`\`\`
${glyph.map((r) => '  ' + r.join(' ')).join('\n')}
\`\`\`
~ sea  . sand  # cobble quay

## Layout
Townhouses and cottages stand in the north-west; the lighthouse (focal) stands in the north-east beside a beached
merchant ship. A cobble-quay basin in the south-east holds piers, docks, rowboats, and a longship. Market stalls and
carts stand on the west shore. Crates, barrels, and nets line the quays.

## Tally
| piece | count |
|---|---|
${Object.entries(tally).sort((a, b) => b[1] - a[1]).map(([k, v]) => `| ${k} | ${v} |`).join('\n')}

Total: ${places.length}
`);
console.log('places', places.length);
