#!/usr/bin/env node
// Desert city map designer. 28 m x 24 m: 14 x 12 tiles of 2 m. Tile centers x -13..13, z -11..11.
// Anchor: docs/map-mockups/desert-city.jpg. Walls are sandstone-wall (2 m wide, 1.5 m tall, thin, along X at yaw 0).
// Writes scenes/maps/desert-city.ts and docs/map-mockups/desert-city.md.
import { writeFileSync } from 'node:fs';

const places = [];
const put = (asset, x, z, o = {}) => {
  const p = { asset, at: [x, o.y ?? 0, z] };
  if (o.yaw) p.yaw = o.yaw;
  if (o.scale) p.scale = o.scale;
  places.push(p);
};

// Wall run between two points on even grid lines; skip = list of segment centers (x or z) left open.
const wallRun = (x1, z1, x2, z2, skip = [], inset = 0) => {
  if (z1 === z2) {
    for (let x = x1 + 1; x < x2; x += 2) if (!skip.includes(x)) put('sandstone-wall', x, z1 + inset);
  } else {
    for (let z = z1 + 1; z < z2; z += 2) if (!skip.includes(z)) put('sandstone-wall', x1 + inset, z, { yaw: 90 });
  }
};
const roof = (x0, z0, x1, z1) => {
  for (let x = x0 + 1; x < x1; x += 2) for (let z = z0 + 1; z < z1; z += 2) put('desert-ground', x, z, { y: 1.5 });
};
// House: walls on the rectangle, a door gap on the south wall, a flat sand roof.
const house = (x0, z0, x1, z1, doorX) => {
  wallRun(x0, z0, x1, z0);
  wallRun(x0, z1, x1, z1, [doorX]);
  wallRun(x0, z0, x0, z1);
  wallRun(x1, z0, x1, z1);
  roof(x0, z0, x1, z1);
};

// --- ground: sand everywhere, sand plaza around the fountain, a paved street to the gate ---
const plaza = (x, z) => false;
for (let x = -13; x <= 13; x += 2)
  for (let z = -11; z <= 11; z += 2) put(plaza(x, z) ? 'marble-floor' : 'desert-ground', x, z);

// --- city wall (perimeter), caravan gate in the south wall at x = -6 ---
wallRun(-14, -12, 14, -12, [], 0.1);
wallRun(-14, 12, 14, 12, [-7, -5], -0.1);
wallRun(-14, -12, -14, 12, [], 0.1);
wallRun(14, -12, 14, 12, [], -0.1);
put('wall-gate', -6, 12.2);
put('lantern', -8.2, 11.2); put('lantern', -3.8, 11.2);
put('banner', -8.4, 10.6); put('banner', -3.6, 10.6);

// --- towers: tall central-north tower, domed corner towers ---
put('tower', 0, -10, { scale: 1 });
put('tower', -11.5, -9.5, { scale: 0.6 });
put('tower', 11.5, -9.8, { scale: 0.6 });

// --- west bazaar house (arcade with awnings facing the plaza), east gate house ---
for (const x of [-10, -6, 6, 10]) put('sandstone-house', x, -6, { yaw: 0 });
for (const x of [-10, 6, 10]) put('sandstone-house', x, 7, { yaw: 180 });
put('sandstone-house', -11.8, -0.5, { yaw: 90 });
put('sandstone-house', 11.8, 0.5, { yaw: 270 });
put('lantern', -8.0, -3.6); put('lantern', 8.0, -3.6);

// small house west and a ruin-like compound in the SE

put('barrel', -10.9, 0.0); put('crate', -7.9, -0.6); put('sack', 8.2, 9.2); put('jar', -5.4, 9.3);
// --- oasis fountain focal ---
put('fountain', 0, 0, { scale: 1.5 });
put('palm-tree', -2.6, -1.9, { yaw: 20 }); put('palm-tree', 2.7, 1.8, { yaw: 140 }); put('palm-tree', 2.4, -2.2, { yaw: 250 });
put('lantern', -3.3, 2.7); put('lantern', 3.3, -2.8);
put('statue', -3.4, -2.6, { yaw: 200, scale: 0.8 });

// --- bazaar (west plaza and street) ---
put('market-tent', -8.4, 0.2, { yaw: 0 });
put('market-tent', -3.9, 8.6, { yaw: 0 });
put('market-cart', -6.9, 3.4, { yaw: 40 });
put('market-cart', 4.8, 4.4, { yaw: 300 });
put('rug', -8.4, 1.4); put('rug', -3.9, 9.8);

// --- caravan yard by the gate (east of the street) ---
put('sand-dune', 4, 9, { scale: 0.8, yaw: 20 });
put('well', 7.6, 2.6, { scale: 0.8 });
put('barrel', 8.6, 3.4);

// --- edge dressing: palms, cacti, lanterns ---
put('palm-tree', -12.6, -3.6, { yaw: 90 });
put('palm-tree', 12.4, 11.2, { yaw: 300 }); put('palm-tree', -12.4, 11.0, { yaw: 40 });
put('cactus', 5.6, 11.0); put('cactus', 12.6, 8.0, { yaw: 120 });
put('cactus', -2.0, -6.6, { yaw: 200 }); put('cactus', 2.4, -6.4, { yaw: 60 });


const body = places.map((p) => {
  const o = [`asset:'${p.asset}'`, `at:[${p.at.map((v) => +v.toFixed(3)).join(',')}]`];
  if (p.yaw) o.push(`yaw:${p.yaw}`);
  if (p.scale) o.push(`scale:${p.scale}`);
  return `  {${o.join(',')}},`;
}).join('\n');
writeFileSync('scenes/maps/desert-city.ts',
`// GENERATED by scripts/design-desert-city.mjs — edit the generator, not this file.
import type { Place } from '../chibi-quest.js';
export function places(): Place[] {
  return [
${body}
  ];
}
`);
const tally = {};
for (const p of places) tally[p.asset] = (tally[p.asset] ?? 0) + 1;
const rows = Object.entries(tally).sort((a, b) => b[1] - a[1]).map(([k, v]) => `| ${k} | ${v} |`).join('\n');
writeFileSync('docs/map-mockups/desert-city.md',
`# Desert city map

28 m x 24 m (14 x 12 tiles). Focal object: the oasis fountain on a sand plaza at the center.
Zones: bazaar (west plaza, street, tents and carts), the two walled houses with awnings (north), the caravan yard and ruin compound (south-east).
Path: caravan gate in the south wall at x=-6, paved street north to the plaza.
Walls are sandstone-wall; house roofs are desert-ground slabs at y=1.5. Anchor: desert-city.jpg.
Missing: camel (no asset), dome roofs (the tower stands in for domes).

Total placements: ${places.length}

| asset | count |
| --- | --- |
${rows}
`);
console.log('placements', places.length);
