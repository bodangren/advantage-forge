#!/usr/bin/env node
// Mausoleum map designer: 14 m x 12 m marble hall, central tomb on a two-step dais,
// colonnades, wall niches with coffins, barred inner door in the north wall.
// North = -Z, east = +X. Floor tiles: x centers -6..6, z centers -5..5 (2 m tiles).
import { writeFileSync } from 'node:fs';

const places = [];
const tally = {};
const put = (asset, x, z, o = {}) => {
  const p = { asset, at: [x, o.y ?? 0, z] };
  if (o.yaw) p.yaw = o.yaw;
  if (o.scale) p.scale = o.scale;
  places.push(p);
  tally[asset] = (tally[asset] ?? 0) + 1;
};
const XS = [-6, -4, -2, 0, 2, 4, 6];
const ZS = [-5, -3, -1, 1, 3, 5];

// Floor: stone-floor, with a few floor-cracked patches near the dais.
const cracked = new Set(['-4,-1', '4,1', '-2,3', '2,-3', '0,-3', '-4,3', '4,-3']);
for (const x of XS) for (const z of ZS) put(cracked.has(`${x},${z}`) ? 'floor-cracked' : 'stone-floor', x, z);
// Three-step dais: 6x4 at top y 0.3, then a 2x4 stack to y 0.6 and 0.9; stairs on the south face.
for (const x of [-2, 0, 2]) for (const z of [-1, 1]) put('stone-floor', x, z, { y: 0.3 });
for (const y of [0.6, 0.9]) for (const z of [-1, 1]) put('stone-floor', 0, z, { y });
put('stairs-stone', 0, 2.75, { scale: 0.9 });
put('sarcophagus', 0, 0, { y: 0.9, yaw: 90, scale: 1.5 });
for (const sx of [-1, 1]) {
  put('statue', sx * 2.6, -1.5, { y: 0.3, scale: 0.6 });
  put('statue', sx * 2.6, 1.5, { y: 0.3, scale: 0.6 });
  put('candelabra', sx * 2.6, 0, { y: 0.3, scale: 2.2 });
  put('candle-cluster', sx * 0.8, 1.7, { y: 0.9, scale: 1.4 });
  put('candle-cluster', sx * 0.8, -1.7, { y: 0.9, scale: 1.4 });
}
// Rug runner from the south entry to the stairs.
put('rug', 0, 4.4, { yaw: 90 });
put('rug', 0, 5.4, { yaw: 90 });

// North wall: two courses high, three arched bays (statue, coffin, barred gate).
for (const x of [-4, -2, 0, 2]) { put('wall', x, -6); put('wall', x, -6, { y: 1.2 }); }
put('wall', 4, -6, { y: 1.2 });
put('iron-door', 4, -5.95);
put('cell-bars', 4, -5.45);
for (const x of [-4, 0, 4]) put('arch', x, -5.55);
put('statue', -4, -5.2, { scale: 0.7 });
put('sarcophagus', 0, -5.2, { scale: 0.7 });
put('statue', -1.5, -5.1, { scale: 0.55 });
put('statue', 1.5, -5.1, { scale: 0.55 });
// South and east walls are low; west wall is tall.
for (const x of [-4, -2, 2, 4]) put('wall', x, 6, { yaw: 180 });
const westAlcove = [-3, -1, 1, 3];
const eastAlcove = [-1, 1];
for (const z of [-3, -1, 1, 3]) {
  put(westAlcove.includes(z) ? 'wall-alcove' : 'wall', -7, z, { yaw: 90 });
  put('wall', -7, z, { yaw: 90, y: 1.2 });
}
for (const z of [-3, -1, 1, 3]) put(eastAlcove.includes(z) ? 'wall-alcove' : 'wall', 7, z, { yaw: 270 });
put('wall-corner', -6, -5, { yaw: 180 });
put('wall-corner', -6, -5, { yaw: 180, y: 1.2 });
put('wall-corner', 6, -5, { yaw: 90 });
put('wall-corner', 6, -5, { yaw: 90, y: 1.2 });
put('wall-corner', -6, 5, { yaw: 270 });
put('wall-corner', 6, 5, { yaw: 0 });
for (const x of [-5, -3, 3, 5]) put('pillar', x, 6);
for (const z of [-4, -2, 0, 2, 4]) { put('pillar', -7, z); put('pillar', 7, z); }

// Coffins in the niches with candles at their feet.
for (const z of westAlcove) { put('sarcophagus', -6.0, z, { scale: 0.7 }); put('candle-cluster', -4.9, z + 0.45, { scale: 1.2 }); }
for (const z of eastAlcove) { put('sarcophagus', 6.0, z, { scale: 0.7, yaw: 180 }); put('candle-cluster', 4.9, z + 0.45, { scale: 1.2 }); }
for (const z of [-3, 3]) put('urn', 6.3, z, { scale: 1.3 });
put('urn', 6.3, 5.0, { scale: 1.3 });
put('urn', -6.3, 5.0, { scale: 1.3 });

// Colonnades at x = +-4.5: alternate pillar and column, banners between.
for (const x of [-4.5, 4.5]) {
  [-4, -2, 0, 2, 4].forEach((z, i) => put(i % 2 === 0 ? 'pillar' : 'column', x, z));
  for (const z of [-3, 1]) put('banner', x, z, { yaw: x < 0 ? 90 : 270 });
}
for (const x of [-1.6, 1.6]) put('brazier', x, 5.2, { scale: 1.2 });
for (const x of [-5.2, 5.2]) put('brazier', x, -3.4, { scale: 1.1 });
for (const z of [-4, 4]) { put('candelabra', -6.2, z, { scale: 1.8 }); put('candelabra', 6.2, z, { scale: 1.8 }); }

const total = places.length;
const src = `// GENERATED by scripts/design-mausoleum.mjs — edit the generator, not this file.\nimport type { Place } from '../chibi-quest.js';\nexport function places(): Place[] { return ${JSON.stringify(places)}; }\n`;
writeFileSync('scenes/maps/mausoleum.ts', src);
const doc = `# Mausoleum map\n\nGenerated by scripts/design-mausoleum.mjs. 14 m x 12 m marble hall (x -7..7, z -6..6).\n\n## Layout\n- Floor: 7x6 stone-floor tiles; central tomb (sarcophagus) on a two-step dais.\n- Colonnades of pillars at x = +-4.5 with urns between.\n- West wall: four niches with coffins; east wall: two niches.\n- North wall: barred inner door (cell-bars) at x = 4 flanked by pillars, statues and candelabras.\n- South wall: low, entry gap at x = 0 with braziers.\n\n## Tally (${total} pieces)\n${Object.entries(tally).map(([k, v]) => `- ${k}: ${v}`).join('\n')}\n`;
writeFileSync('docs/map-mockups/mausoleum.md', doc);
console.log(total, tally);
