#!/usr/bin/env node
// Mountain pass map designer (P2, Castle Defense level 3): 12 x 8 tiles of 2 m.
// Cell (c,r) center: x = (c-6.5)*2, z = (r-4.5)*2. +X east, -Z north.
// One winding dirt path west -> east between two cliff rows; stone-ground elsewhere.
import { writeFileSync } from 'node:fs';

const places = [];
const put = (asset, x, z, o = {}) => {
  const p = { asset, at: [x, o.y ?? 0, z] };
  if (o.yaw) p.yaw = o.yaw;
  if (o.scale) p.scale = o.scale;
  places.push(p);
};
const center = (x) => 2.2 * Math.sin(x * 0.27 + 0.5); // long S-curve
const COLS = 12, ROWS = 8;
const X = (c) => (c - 6.5) * 2, Z = (r) => (r - 4.5) * 2;
const BRIDGE_C = 3;

// ground
const glyph = Array.from({ length: ROWS }, () => Array(COLS).fill('.'));
for (let c = 1; c <= COLS; c++)
  for (let r = 1; r <= ROWS; r++) {
    const x = X(c), z = Z(r);
    const cr = center(x) / 2 + 4.5; // path centre in row units
    const onPath = c === BRIDGE_C ? r === Math.round(cr) : Math.abs(r - cr) < 1.0 + (c % 2 ? 0.0 : 0.0);
    if (c === BRIDGE_C && onPath) {
      put('river-straight', x, z); glyph[r - 1][c - 1] = 'V';
    } else if (onPath) { put('dirt-ground', x, z); glyph[r - 1][c - 1] = '='; }
    else put('stone-ground', x, z);
  }
{ const br = Math.round(center(X(BRIDGE_C)) / 2 + 4.5); put('bridge', X(BRIDGE_C), Z(br), { y: 0.02, scale: 0.85 }); }

// cliff walls: north row faces south (yaw 0), south row faces north (yaw 180).
// Each cliff gets a snowbank cap on the green crown; some get a pine or a boulder on top.
let ci = 0;
const cliff = (x, z, yaw, sc) => {
  put('cliff-face', x, z, { yaw, scale: sc });
  const top = 3.0 * sc;
  const k = ci++;
  put('snowbank', x, z, { y: top - 0.1, yaw: k * 53, scale: 1.25 * sc });
  if (k % 3 === 0) put('pine-tree', x + 0.5, z + 0.2, { y: top - 0.1, yaw: k * 29, scale: 0.35 });
  else if (k % 3 === 1) put('boulder', x - 0.4, z, { y: top - 0.1, yaw: k * 41, scale: 0.55 });
};
const wob = [0.5, -0.3, 0.7, 0.0, -0.5, 0.4, 0.2, -0.6, 0.5, 0.0];
for (let i = 0; i < 8; i++) {
  const x = -10.2 + i * 2.95;
  cliff(x, -5.3 + wob[i] * 0.6, (i % 3 - 1) * 6, 0.85 + 0.55 * Math.abs(Math.sin(i * 1.9)));
  cliff(x + 1.3, 5.4 - wob[i + 1] * 0.6, 180 + (i % 3 - 1) * 6, 0.8 + 0.6 * Math.abs(Math.cos(i * 1.6 + 0.5)));
}
for (let i = 0; i < 6; i++) {
  const x = -9.4 + i * 3.8;
  cliff(x, -7.3, 4 * (i % 2 ? 1 : -1), 1.15 + 0.25 * (i % 3) * 0.8);
  cliff(x + 1.6, 7.3, 180, 1.1 + 0.25 * ((i + 1) % 3) * 0.8);
}
cliff(-11.4, -3.6, 90, 1.0); cliff(11.4, -3.6, 270, 1.2);
cliff(-11.4, 3.8, 90, 1.3); cliff(11.4, 3.8, 270, 0.9);

// landmarks
put('milestone', -10.4, center(-10.4) - 2.4, { yaw: 20 });
put('signpost', -10.4, center(-10.4) + 2.4, { yaw: 160 });

put('dead-tree', 10.6, -3.8, { yaw: 120 });
put('dead-tree', -10.4, 3.4, { yaw: 40 });

// rocks and snow at cliff bases and verges (never on the path)
const verge = [
  [-8.4, -3.7], [-5.2, -3.9], [-2.0, -3.6], [1.3, -4.0], [4.6, -3.6], [8.0, -4.0],
  [-7.6, 3.9], [-4.0, 4.0], [-0.6, 3.9], [2.8, 3.7], [6.4, 4.0], [9.6, 3.8],
];
verge.forEach(([x, z], i) => {
  put(i % 3 === 0 ? 'rock-cluster' : 'boulder', x, z, { yaw: i * 47, scale: 0.8 + (i % 4) * 0.12 });
});
const snow = [[-7, -3.4], [-3.4, -4.2], [3, -3.3], [6.2, -4.3], [-6, 4.3], [0.8, 4.4], [4.6, 4.2], [8, 3.4]];
snow.forEach(([x, z], i) => put('snowbank', x, z, { yaw: i * 61 }));

// pines on the rear ground between wall rows and map edge
const pines = [[-11.0, -6.0], [-5.0, -6.6], [3.6, -6.6], [10.8, -6.2], [-11.0, 6.2], [-2.0, 6.6], [6.0, 6.6], [10.8, 6.2], [-11.4, 0], [11.4, 0]];
pines.forEach(([x, z], i) => put('pine-tree', x, z, { yaw: i * 37, scale: 0.55 + (i % 3) * 0.08 }));

// glyphs and docs
const mark = (x, z, g) => { const c = Math.round(x / 2 + 6.5), r = Math.round(z / 2 + 4.5); if (c >= 1 && c <= COLS && r >= 1 && r <= ROWS) glyph[r - 1][c - 1] = g; };
mark(-10.4, center(-10.4) - 2.4, 'M'); mark(-10.4, center(-10.4) + 2.4, 'S');

const num = (v) => (Number.isInteger(v) ? String(v) : v.toFixed(2).replace(/0+$/, '').replace(/\.$/, ''));
const fmt = (p) => `  { asset: '${p.asset}', at: [${num(p.at[0])}, ${num(p.at[1])}, ${num(p.at[2])}]${p.yaw ? `, yaw: ${num(p.yaw)}` : ''}${p.scale ? `, scale: ${num(p.scale)}` : ''} },`;
writeFileSync('scenes/maps/mountain-pass.ts', `// GENERATED by scripts/design-mountain-pass.mjs — edit the generator, not this file.
import type { Place } from '../chibi-quest.js';
export function places(): Place[] {
  return [
${places.map(fmt).join('\n')}
  ];
}
`);
const tally = {};
for (const p of places) tally[p.asset] = (tally[p.asset] ?? 0) + 1;
writeFileSync('docs/map-mockups/mountain-pass.md', `# Mountain pass (generated)

GENERATED by scripts/design-mountain-pass.mjs. 12 x 8 tiles of 2 m (24 x 16 m). Castle Defense level 3.

\`\`\`
${glyph.map((r) => '  ' + r.join(' ')).join('\n')}
\`\`\`
= dirt path, V stream under the rope bridge, . stone ground, M milestone, S signpost.

The path winds west to east between two cliff rows. Flat stone ground 2 to 3 m wide
beside the path holds the tower slots. Rocks and snowbanks sit at the cliff bases,
pines stand on the rear ground.

| piece | count |
|---|---|
${Object.entries(tally).sort((a, b) => b[1] - a[1]).map(([k, v]) => `| ${k} | ${v} |`).join('\n')}

Total: ${places.length}.
`);
console.log(glyph.map((r) => r.join(' ')).join('\n'), '\n', places.length, JSON.stringify(tally));
