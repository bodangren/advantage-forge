#!/usr/bin/env node
// Grassland map designer (Castle Defense level 1). Writes scenes/maps/grassland.ts and
// docs/map-mockups/grassland.md. Grid 12 x 10 tiles of 2 m (24 x 20 m).
// Cell (c,r) center: x = (c-6.5)*2, z = (r-5.5)*2. +X east, -Z north.
// Road: enters west edge on row 7, runs east to col 8, ONE bend north, exits the north edge on col 8.
import { writeFileSync } from 'node:fs';

const X = (c) => (c - 6.5) * 2;
const Z = (r) => (r - 5.5) * 2;
const places = [];
const put = (asset, x, z, o = {}) => {
  const p = { asset, at: [x, 0, z] };
  if (o.yaw) p.yaw = o.yaw;
  if (o.scale) p.scale = o.scale;
  places.push(p);
};
let seed = 7;
const rnd = () => ((seed = (seed * 1664525 + 1013904223) >>> 0) / 4294967296);

// --- ground + road ---
const roadAt = (c, r) => {
  if (r === 7 && c >= 1 && c <= 7) return ['dirt-road-straight', 90];
  if (r === 7 && c === 8) return ['dirt-road-corner', 90]; // W + N
  if (c === 8 && r >= 1 && r <= 6) return ['dirt-road-straight', 0];
  return null;
};
for (let c = 1; c <= 12; c++)
  for (let r = 1; r <= 10; r++) {
    const road = roadAt(c, r);
    if (road) put(road[0], X(c), Z(r), { yaw: road[1] });
    else put('grass-ground', X(c), Z(r));
  }

// --- landmarks ---
put('pond', -5, -3.4, { yaw: 10, scale: 1.4 }); // NW pond (focal)
put('oak-tree', -9.2, -6.2, { yaw: 30, scale: 1.4 }); // big oak beside the pond, as in the mockup
for (let k = 0; k < 4; k++) put('fence', -7.4 + k * 1.9, -8.8); // fence run on the north edge
put('signpost', -10.2, 1.4, { yaw: 150 }); // at the road entry
put('hay-bale', -7.6, 8.2, { yaw: 20 });
put('hay-bale', -6.2, 8.5, { yaw: 100 });
put('stump', -8.6, 6.8, { yaw: 60 });

// --- pond zone: rocks and grass ---
put('boulder', -2.9, -4.6, { yaw: 40 });
put('boulder', -7.4, -2.5, { yaw: 120, scale: 0.8 });
put('bush', -2.0, -6.8, { yaw: 60 });

// --- orchard / flower zone (east) ---
const ORCH = [[8.8, -6.4], [10.6, -4.2], [9.4, -1.0], [10.8, 1.6], [10.2, 5.8]];
ORCH.forEach(([x, z], i) => put(i % 2 ? 'apple-tree' : 'birch-tree', x, z, { yaw: i * 70, scale: 0.95 + 0.05 * i }));
[[7.4, -6.6], [8.8, -3.2], [10.8, -0.4], [9.0, 3.2], [10.6, 3.8], [8.2, 8.2]].forEach(([x, z], i) => put('wildflowers', x, z, { yaw: i * 55 }));
put('boulder', 10.9, -7.2, { yaw: 200 });
put('boulder', 8.6, 6.2, { yaw: 300, scale: 0.8 });
put('hay-bale', 9.8, 8.2, { yaw: 160 });

// --- west meadow (flowers off the tower slots) ---
[[-9.4, -0.4], [-4.0, 1.0], [-1.2, -7.6]].forEach(([x, z], i) => put('wildflowers', x, z, { yaw: i * 80 }));
[[-4.2, 4.8], [0.6, 8.6]].forEach(([x, z], i) => put('tall-grass', x, z, { yaw: i * 70 }));

// --- edge dressing: trees and bushes on the border, gaps at the road mouths ---
const clear = (x, z) =>
  !(Math.abs(x - 3) < 1.8 && z < -5) && !(Math.abs(z - 3) < 1.8 && x < -9) && // road mouths
  Math.hypot(x + 5, z + 3.4) > 3.6 && // pond
  !places.some((p) => p.asset !== 'grass-ground' && !p.asset.startsWith('dirt-road') && Math.hypot(p.at[0] - x, p.at[2] - z) < 1.5);
const treeTypes = ['oak-tree', 'apple-tree', 'birch-tree'];
let t = 0;
const edge = [];
for (let x = -10.5; x <= 10.5; x += 2.4) { edge.push([x, -9.2]); edge.push([x, 9.2]); }
for (let z = -6.8; z <= 6.8; z += 2.4) { edge.push([-11.2, z]); edge.push([11.2, z]); }
for (const [x0, z0] of edge) {
  const x = Math.max(-11.3, Math.min(11.3, x0 + (rnd() - 0.5) * 0.8));
  const z = Math.max(-9.3, Math.min(9.3, z0 + (rnd() - 0.5) * 0.6));
  if (!clear(x, z)) continue;
  if (x > 4.4 && x < 10 && z > -8 && z < 8) continue;
  t++;
  put(t % 3 === 0 ? 'bush' : treeTypes[t % 3], x, z, { yaw: Math.round(rnd() * 360), scale: 0.85 + rnd() * 0.3 });
}
// bushes tucked between border trees
for (let x = -9.4; x <= 10; x += 4.8) for (const z of [-9.6, 9.6]) if (clear(x, z)) put('bush', x, z, { yaw: Math.round(rnd() * 360), scale: 0.8 });

// --- emit ---
const num = (v) => (Number.isInteger(v) ? String(v) : v.toFixed(2).replace(/0+$/, '').replace(/\.$/, ''));
const fmt = (p) => `    { asset: '${p.asset}', at: [${num(p.at[0])}, ${num(p.at[1])}, ${num(p.at[2])}]${p.yaw ? `, yaw: ${p.yaw}` : ''}${p.scale ? `, scale: ${num(p.scale)}` : ''} },`;
writeFileSync('scenes/maps/grassland.ts', `// GENERATED by scripts/design-grassland.mjs — edit the generator, not this file.
import type { Place } from '../chibi-quest.js';
export function places(): Place[] {
  return [
${places.map(fmt).join('\n')}
  ];
}
`);
const tally = {};
for (const p of places) tally[p.asset] = (tally[p.asset] ?? 0) + 1;
writeFileSync('docs/map-mockups/grassland.md', `# Grassland map (generated)

GENERATED by scripts/design-grassland.mjs. Grid 12 x 10 tiles of 2 m (24 x 20 m); Castle Defense level 1.
Cell (c,r) center: x = (c-6.5)*2, z = (r-5.5)*2.

## Layout
Dirt road enters the west edge on row 7, runs east, bends once north at col 8, and exits the north edge.
Open grass stays clear on both sides for tower slots. Zones: NW pond with oak and fence, east orchard
with wildflowers, south-west hay and stump by the road entry. Trees and bushes ring the border.

## Tally (${places.length} pieces)
${Object.entries(tally).sort((a, b) => b[1] - a[1]).map(([k, v]) => `- ${k}: ${v}`).join('\n')}
`);
console.log(places.length, JSON.stringify(tally));
