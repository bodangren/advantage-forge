#!/usr/bin/env node
// Bathhouse map designer: 14 m x 12 m hall (7 x 6 tiles of 2 m), steam pool in the middle.
// Tile (c,r) center: x = (c-4)*2 (c 0..6), z = (r-2.5)*2 (r 0..5). North = -Z.
// Writes scenes/maps/bathhouse.ts and docs/map-mockups/bathhouse.md.
import { writeFileSync } from 'node:fs';

const places = [];
const put = (asset, x, z, o = {}) => {
  const p = { asset, at: [x, o.y ?? 0, z] };
  if (o.yaw) p.yaw = o.yaw;
  if (o.scale) p.scale = o.scale;
  places.push(p);
};

// Floors: water 3x2 tiles, stone rim ring, tile floor elsewhere.
const waterX = [-2, 0, 2], waterZ = [-1, 1];
for (let c = 0; c < 7; c++)
  for (let r = 0; r < 6; r++) {
    const x = (c - 3) * 2, z = (r - 2.5) * 2;
    const water = waterX.includes(x) && waterZ.includes(z);
    const rim = Math.abs(x) <= 4 && Math.abs(z) <= 3;
    put(water ? 'sea-water' : 'marble-floor', x, z);
  }
// entrance apron
for (const x of [-2, 0, 2]) put('marble-floor', x, 7);

// Walls (plaster, 2 m, along X). North, west, east full; south has a door gap in the middle.
for (let x = -6; x <= 6; x += 2) put(x === 0 ? 'sandstone-wall' : 'sandstone-wall', x, -6);
for (let z = -5; z <= 5; z += 2) {
  put(z === -1 ? 'sandstone-wall' : 'sandstone-wall', -7, z, { yaw: 90 });
  put(z === 1 ? 'sandstone-wall' : 'sandstone-wall', 7, z, { yaw: 90 });
}
for (const x of [-6, -4, 4, 6]) put('sandstone-wall', x, 6);
put('plaster-wall-door', -2, 6);
put('plaster-wall-door', 2, 6);
// Corner and door columns
for (const [x, z] of [[-7, -6], [7, -6], [-7, 6], [7, 6], [-6, -6], [6, -6], [0, 6], [-7, 0], [7, 0], [-3, -6], [3, -6]]) put('column', x, z);
// Pool columns at the rim corners
for (const [x, z] of [[-1.8, -5.5], [1.8, -5.5], [-4.6, 5.5], [4.6, 5.5]]) put('column', x, z);
put('fountain', 0, -4.9);
put('statue', -5.3, -5.1); put('statue', 5.3, -5.1, { yaw: 0 });

// Zone 1 NW: massage corner (table, stool, shelf of towels, braziers)
put('bed', -5.2, -4, { yaw: 90 });
put('stool', -3.7, -4.3); put('stool', -6.3, -2.2);
put('shelf', -6.5, -5.4); put('shelf', -3.2, -5.6); put('shelf', 3.4, -5.6); put('shelf', 6.4, -5.4);
put('brazier', -6.3, -3.2); put('brazier', 6.3, -3.2); put('brazier', -6.3, 3.2); put('brazier', 6.3, 3.2);
// Zone 2 W/E: benches and buckets for bathers
for (const z of [-1.6, 0.8, 3.2]) put('bench', -6.4, z, { yaw: 90 });
for (const z of [0.8, 3.2]) put('bench', 6.4, z, { yaw: 270 });
put('table', 5.6, -4.6); put('chair', 4.4, -4.5, { yaw: 180 });
// Zone 3 S: attendant desk and entrance
put('healer', 3.5, 4.8, { yaw: 180 });
put('table', 4.6, 4.9); put('rug', 0, 4.6); put('rug', 0, 7.6);

// Rim dressing: candles, buckets, jars, baskets around the pool
const rimTop = [-4.8, -3.2, -1.6, 1.6, 3.2, 4.8];
rimTop.forEach((x, i) => { put('candle', x, -3.75 + (i % 2) * 0.15); put('candle', x, 3.75 - (i % 2) * 0.15); });
[-1.8, 0, 1.8].forEach((z) => { put('candle', -4.65, z); put('candle', 4.65, z); });
put('bucket', -3.6, 3.7); put('bucket', 3.6, 3.6); put('bucket', -4.7, -2.2); put('bucket', 4.7, 2.2);
put('bucket', -6.4, 4.7); put('bucket', 6.2, 4.6); put('bucket', -6.5, -0.2); put('bucket', 6.5, -1.4);
put('wicker-basket', 6.4, 2); put('basket', -6.3, 2); put('basket', 6.3, -2.4);
put('jar', -6.4, -6.0 + 1.6); put('urn', 6.3, 5.0); put('jar', -2.4, 5.6); put('urn', -5.7, 5.2);
put('barrel', 6.4, -4.0); put('barrel', -6.4, 4.0); put('barrel', 5.6, 5.6);
// Wall lights (mounted at wall height; wall-sconce mounts on its back)
for (const x of [-5, -1.6, 1.6, 5]) put('wall-sconce', x, -5.85, { y: 0.8 });
for (const z of [-3, 3]) { put('wall-sconce', -6.85, z, { y: 0.8, yaw: 270 }); put('wall-sconce', 6.85, z, { y: 0.8, yaw: 90 }); }
put('lantern', -2.6, 5.4); put('lantern', 2.6, 5.4); put('lantern', -1.6, 3.7); put('lantern', 1.6, -3.7);
// Steam over the pool
// Floor items: sacks, logs for the stoves, more candles
put('stool', -4.5, 5.2); put('sack', 6, 4.2); put('sack', 5.5, 4.6); put('wood-log', 6.1, 3.9); put('bowl', 4.2, 4.7);
put('quench-tub', -5.9, 1.2);
put('fern', -6.3, -4.8); put('fern', 6.3, 5.4); put('fern', -6.4, 5.5);
// Scale figures
put('villager', -3.8, 3.5, { yaw: 160 }); put('adventurer', 0.2, 8.6, { yaw: 180 });

const count = {};
for (const p of places) count[p.asset] = (count[p.asset] ?? 0) + 1;
const num = (v) => (Number.isInteger(v) ? String(v) : v.toFixed(2).replace(/0+$/, '').replace(/\.$/, ''));
const fmt = (p) => `  { asset: '${p.asset}', at: [${p.at.map(num).join(', ')}]${p.yaw ? `, yaw: ${p.yaw}` : ''}${p.scale ? `, scale: ${p.scale}` : ''} },`;
writeFileSync('scenes/maps/bathhouse.ts', `// GENERATED by scripts/design-bathhouse.mjs — edit the generator, not this file.
import type { Place } from '../chibi-quest.js';
export function places(): Place[] {
  return [
${places.map(fmt).join('\n')}
  ];
}
`);
writeFileSync('docs/map-mockups/bathhouse.md', `# Bathhouse map (generated)

GENERATED by scripts/design-bathhouse.mjs. 14 m x 12 m hall, 7 x 6 tiles of 2 m.
Focal object: the 6 m x 4 m steam pool (sea-water tiles) in a stone-floor rim.
Zones: NW massage corner (bed, stools, shelves), W/E bench rows with buckets, S entrance with attendant desk.
Path: south door, rug, around the pool rim. Pieces: ${places.length}.

| asset | count |
|---|---|
${Object.entries(count).sort().map(([a, n]) => `| ${a} | ${n} |`).join('\n')}
`);
console.log(places.length, 'pieces');
const missing = [...new Set(places.map((p) => p.asset))].filter((a) => !require_exists(a));
function require_exists(a) { return existsSync(`out/${a}/${a}.glb`); }
console.log('missing:', missing.join(', ') || 'none');
import { existsSync } from 'node:fs';
