#!/usr/bin/env node
// Goblin camp map designer (P2 map): 18 x 16 m forest clearing on one dirt floor.
// Tiles: 10 x 9 of 2 m (x -10..10, z -9..9), the extra ring carries the treeline.
// Palisade of wood-wall on N, E, W and S (gate gap at x -2..2); huts on the north side,
// tents on the west, loot on the east; campfire + cooking pot at the center.
// Writes scenes/maps/goblin-camp.ts and docs/map-mockups/goblin-camp.md.
import { writeFileSync } from 'node:fs';

const places = [];
const put = (asset, x, z, o = {}) => {
  const p = { asset, at: [x, o.y ?? 0, z] };
  if (o.yaw) p.yaw = o.yaw;
  if (o.scale) p.scale = o.scale;
  places.push(p);
};

// ground: one material
for (let i = 0; i < 10; i++) for (let j = 0; j < 9; j++) put('dirt-ground', -9 + i * 2, -8 + j * 2);

// palisade (wood-wall faces +Z at yaw 0; yaw 180 inward-facing north wall, 270 east, 90 west)
for (let x = -7; x <= 7; x += 2) put('wood-wall', x, -7.3, { yaw: 180 });
for (const x of [-7, -5, -3, 3, 5, 7]) put('wood-wall', x, 7.3, { yaw: 0 });
for (let z = -5; z <= 5; z += 2) { put('wood-wall', 8.3, z, { yaw: 270 }); put('wood-wall', -8.3, z, { yaw: 90 }); }
// corners: one stump post each side of the corner, plus the gate torches
for (const [x, z] of [[-8.3, -7.3], [8.3, -7.3], [-8.3, 7.3], [8.3, 7.3]]) put('tree-stump', x, z, { scale: 1.6 });
put('torch', -2.5, 6.6); put('torch', 2.5, 6.6);

// zone 1: central fire (focal)
put('campfire', 0, 0.5, { scale: 2.2 });
put('cooking-pot', 1.6, 0.0, { yaw: 200, scale: 1.2 });
put('meat', -1.4, 1.5, { yaw: 40, scale: 1.4 });
put('fallen-log', -2.4, 0.6, { yaw: 90 });
put('fallen-log', 0.3, 2.9, { yaw: 0 }); 
put('stump', 2.2, -0.9); put('stump', -1.5, -1.0);
put('goblin-warrior', -1.6, 1.8, { yaw: 130 });
put('goblin-warrior', 2.6, 0.9, { yaw: 250 });
put('goblin-archer', 4.4, 4.0, { yaw: 200 });

// zone 2: huts and chieftain's yurt along the north wall
put('hut', -6, -4.3, { yaw: 20 });
put('yurt', 0, -4.6, { yaw: 0 });
put('hut', 6, -4.2, { yaw: -20 });
put('goblin-king', 0, -2.3, { yaw: 0 });
put('banner', -2.9, -2.6, { yaw: 10 }); put('banner', 2.9, -2.6, { yaw: -10 });
put('gibbet', 4.0, -1.4, { yaw: 200 });
put('bone-pile', 5.2, -1.0, { yaw: 30 }); put('bone-pile', -4.6, -1.6, { yaw: 120 });
put('monster-bone', 3.1, -1.3, { yaw: 60 });
put('barrel', -4.2, -6.3); put('barrel', -3.6, -6.2, { yaw: 40 });
put('sack', 3.3, -6.3, { yaw: 20 }); put('sack', 3.8, -6.2, { yaw: 90 });
put('crate', 7.0, -6.2, { yaw: 10 }); put('crate', 7.0, -6.2, { yaw: 10, y: 0.41 });

// zone 3: west tents + east loot yard
put('tent', -6.6, 1.8, { yaw: 80 });
put('tent', -6.4, 4.8, { yaw: 100 });
put('goblin-warrior', -4.8, 3.3, { yaw: 270 });
put('sack', -7.4, 6.2, { yaw: 30 }); put('sack', -7.0, 6.3, { yaw: 140 });
put('crate', 7.2, 1.0, { yaw: 350 }); put('crate', 7.2, 1.0, { yaw: 350, y: 0.41 });
put('crate', 7.3, 2.0, { yaw: 15 });
put('barrel', 7.4, 3.9); put('barrel', 6.7, 4.4, { yaw: 60 });
put('sack', 7.2, 5.6, { yaw: 200 }); put('sack', 6.6, 6.0, { yaw: 70 });
put('wood-log', 6.8, -2.2, { yaw: 95 }); put('wood-log', 6.9, -2.7, { yaw: 100 });
put('bone-pile', -7.0, 0.3, { yaw: 200 });

// dressing along the inside of the walls
for (const [x, z] of [[-6, -6.4], [0.4, -6.5], [6, 6.5], [-5.5, 6.4], [7.4, -0.6]]) put('bush', x, z);


// treeline outside the palisade
const T = [];
for (let x = -9; x <= 9; x += 1.9) { T.push([x, -8.5]); if (Math.abs(x) > 2.8) T.push([x + 0.6, 8.3]); }
for (let z = -6.5; z <= 6.5; z += 2.1) { T.push([-9.3, z]); T.push([9.3, z]); }
T.forEach(([x, z], i) => {
  const a = i % 3 === 0 ? 'oak-tree' : 'pine-tree';
  put(a, +x.toFixed(2), +z.toFixed(2), { yaw: (i * 67) % 360, scale: (z > 7 ? 0.65 : 0.8) + ((i * 37) % 30) / 100 });
});
put('dead-tree', 9.4, 7.8, { yaw: 40 });

const num = (v) => (Number.isInteger(v) ? String(v) : v.toFixed(2).replace(/0+$/, '').replace(/\.$/, ''));
const fmt = (p) => `  { asset: '${p.asset}', at: [${num(p.at[0])}, ${num(p.at[1])}, ${num(p.at[2])}]${p.yaw ? `, yaw: ${p.yaw}` : ''}${p.scale ? `, scale: ${p.scale}` : ''} },`;
writeFileSync('scenes/maps/goblin-camp.ts', `// GENERATED by scripts/design-goblin-camp.mjs — edit the generator, not this file.
import type { Place } from '../chibi-quest.js';
export function places(): Place[] {
  return [
${places.map(fmt).join('\n')}
  ];
}
`);
const tally = {};
for (const p of places) tally[p.asset] = (tally[p.asset] ?? 0) + 1;
writeFileSync('docs/map-mockups/goblin-camp.md', `# Goblin camp (generated)

GENERATED by scripts/design-goblin-camp.mjs.

18 x 16 m clearing on 10 x 9 dirt-ground tiles. Wood-wall palisade on all sides with a south gate (x -2..2, torches).
Central campfire with pot, logs, stumps and two goblin warriors. North: two huts and the yurt with the goblin king and banners.
West: tents, cage, sacks. East: crates, barrels, sacks, logs, gibbet. Oaks and pines ring the outside.

| asset | count |
|---|---|
${Object.entries(tally).sort((a, b) => b[1] - a[1]).map(([k, v]) => `| ${k} | ${v} |`).join('\n')}

Total: ${places.length} placements.
`);
console.log(places.length, JSON.stringify(tally));
