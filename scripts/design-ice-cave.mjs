#!/usr/bin/env node
// Ice cave map designer: 16 m x 14 m frozen cavern (8 x 7 snow-ground tiles) with a wall ring.
// Writes scenes/maps/ice-cave.ts and docs/map-mockups/ice-cave.md. +X east, -Z north.
import { writeFileSync } from 'node:fs';

const places = [];
const put = (asset, x, z, o = {}) => {
  const p = { asset, at: [x, o.y ?? 0, z] };
  if (o.yaw) p.yaw = o.yaw;
  if (o.scale) p.scale = o.scale;
  places.push(p);
};
let seed = 7;
const rnd = () => ((seed = (seed * 16807) % 2147483647) / 2147483647);

// Ground: whole footprint plus a half ring under the wall.
for (let c = -5; c <= 5; c++) for (let r = -4; r <= 4; r++) {
  const x = c * 2 - 0, z = r * 2;
  if (Math.abs(x) > 9 || Math.abs(z) > 7.5) continue;
  put('snow-ground', x, z);
}

// Cave wall: ice-spires and snowbanks packed shoulder to shoulder on the north and west.
const sc = (i) => 1.5 + ((i * 37) % 8) / 8 * 0.7;
let i = 0;
for (let x = -8.2; x <= 8.4; x += 1.5) {
  put('ice-spire', x, -6.9, { scale: sc(i), yaw: (i * 71) % 360 });
  put('ice-spire', x + 0.7, -5.6, { scale: sc(i + 3) * 0.85, yaw: (i * 53) % 360 });
  put('snowbank', x + 0.3, -4.7, { scale: 1.5, yaw: (i % 2) * 180 });
  i++;
}
for (let z = -4; z <= 7; z += 1.5) {
  put('ice-spire', -8.5, z, { scale: sc(i), yaw: (i * 71) % 360 });
  put('ice-spire', -7.2, z + 0.7, { scale: sc(i + 3) * 0.8, yaw: (i * 53) % 360 });
  put('snowbank', -6.2, z + 0.3, { scale: 1.5, yaw: 90 });
  i++;
}
// East side: low drifts with a spire cluster in the NE corner.
for (let z = -3; z <= 7; z += 2) put('snowbank', 8.4, z, { scale: 1.5, yaw: 90 });
for (const [x, z, s] of [[8.2, -3.4, 1.6], [8.3, -1.6, 1.2], [8.2, 0.4, 0.9]]) put('ice-spire', x, z, { scale: s, yaw: i++ * 40 });
// South edge: low drifts only.
for (let x = -7; x <= 7; x += 3) put('snowbank', x, 7.3, { scale: 1.3, yaw: 0 });

// Frozen pool: ring of small ice-spires around a clear flat clearing, dais and chest in the middle.
const PC = [-3, 1.8];
for (let k = 0; k < 12; k++) {
  const a = (k / 12) * Math.PI * 2;
  put('ice-spire', PC[0] + Math.cos(a) * 2.7, PC[1] + Math.sin(a) * 2.2, { scale: 0.7 + (k % 3) * 0.15, yaw: k * 60 });
}
put('stone-ground', PC[0], PC[1], { scale: 0.6 });
put('chest', PC[0], PC[1], { yaw: 20, scale: 1.2 });

// Braziers among the crystals (light) and crystal groups of 3 at the wall base.
for (const [x, z] of [[-6, -3.6], [-1, -4.3], [3.2, -4], [6.2, -2.6], [-5.2, 4.6], [5.8, 5]]) put('brazier', x, z);
const groups = [[-4.6, -4.4], [0.8, -4.4], [5.2, -3.6], [-5.6, 0], [-5.6, 4.4], [7, 2.4]];
groups.forEach(([x, z], g) => {
  put('crystal-cluster', x, z, { scale: 1.8, yaw: g * 50 });
  put('crystal-shard', x + 0.7, z + 0.3, { scale: 2.2, yaw: g * 90 });
  put('crystal-cluster', x - 0.6, z + 0.5, { scale: 1.4, yaw: g * 30 + 90 });
});

// Drifts, stalagmite groups, and boulder rings on the open ground (the path band x 2..4.5 stays clear).
for (const [x, z, s] of [[-0.5, -1.5, 1.2], [0, 3.2, 1.3], [-6, 6.2, 1.4], [-2.5, 6, 1.3], [0.2, 5.6, 1.1], [6.8, 5.8, 1.3], [6.6, 1, 1.2], [-0.6, 0.6, 1.0], [6.2, -0.4, 1.2], [-3, -2.2, 1.1]])
  put('snowbank', x, z, { scale: s, yaw: i++ * 67 });
for (const [x, z] of [[1, -2.8], [-0.6, 4.6], [6, 3.4], [-6, 2.6]]) {
  put('stalagmite', x, z, { scale: 1.0, yaw: i++ * 50 });
  put('stalagmite', x + 0.9, z + 0.4, { scale: 0.7, yaw: i++ * 50 });
  put('stalagmite', x - 0.6, z + 0.8, { scale: 0.8, yaw: i++ * 50 });
}
for (const [x, z] of [[0.8, 1.2], [6, 6.4]])
  for (let k = 0; k < 5; k++) put('boulder', x + Math.cos(k * 1.26) * 0.9, z + Math.sin(k * 1.26) * 0.9, { scale: 0.6, yaw: k * 70 });

// Cave doors tucked into the groves.
put('door', -4.2, -6.2, { scale: 1.0 });
put('door', 7.6, -2.6, { yaw: 270, scale: 1.0 });

const num = (v) => (Number.isInteger(v) ? String(v) : v.toFixed(2).replace(/0+$/, '').replace(/\.$/, ''));
const fmt = (p) => `    { asset: '${p.asset}', at: [${num(p.at[0])}, ${num(p.at[1])}, ${num(p.at[2])}]${p.yaw ? `, yaw: ${p.yaw}` : ''}${p.scale ? `, scale: ${p.scale}` : ''} },`;
writeFileSync('scenes/maps/ice-cave.ts', `// GENERATED by scripts/design-ice-cave.mjs — edit the generator, not this file.
import type { Place } from '../chibi-quest.js';

export function places(): Place[] {
  return [
${places.map(fmt).join('\n')}
  ];
}
`);
const tally = {};
for (const p of places) tally[p.asset] = (tally[p.asset] ?? 0) + 1;
writeFileSync('docs/map-mockups/ice-cave.md', `# Ice cave — map plan (generated)

GENERATED by \`scripts/design-ice-cave.mjs\`. 16 m x 14 m snow-ground with a ice-spire and snowbank cave wall.

Zones: NW and NE ice-spire groves with doors, a frozen pool (blue puddles) with the chest on its west bank,
a clear snow path from the south entry curving north-east, crystal clusters at the wall bases.

## Tally (${places.length} placements)

${Object.entries(tally).sort().map(([k, v]) => `- ${k}: ${v}`).join('\n')}
`);
console.log(places.length, JSON.stringify(tally));
