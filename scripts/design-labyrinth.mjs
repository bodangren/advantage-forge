#!/usr/bin/env node
// Labyrinth map designer: 8x8 cell maze (2 m cells, 16 m square), stone outer ring,
// hedge inner walls, start gate south, portal goal in the 2x2 centre chamber.
// Writes scenes/maps/labyrinth.ts and docs/map-mockups/labyrinth.md.
import { writeFileSync } from 'node:fs';

const N = 8;
let seed = Number(process.argv[2] ?? 11);
const rnd = () => ((seed = (seed * 1664525 + 1013904223) >>> 0) / 4294967296);
const cx = (c) => (c - 3.5) * 2, cz = (r) => (r - 3.5) * 2;
const id = (c, r) => r * N + c;
// walls: H[r][c] = wall on north side of cell (c,r), r=0..8; V[r][c] = wall on west side, c=0..8
const H = Array.from({ length: N + 1 }, () => Array(N).fill(true));
const V = Array.from({ length: N }, () => Array(N + 1).fill(true));
const par = Array.from({ length: N * N }, (_, i) => i);
const find = (a) => (par[a] === a ? a : (par[a] = find(par[a])));
const join = (a, b) => { a = find(a); b = find(b); if (a === b) return false; par[a] = b; return true; };
// centre chamber
H[4][3] = H[4][4] = false; V[3][4] = V[4][4] = false;
join(id(3, 3), id(4, 3)); join(id(3, 4), id(4, 4)); join(id(3, 3), id(3, 4)); join(id(4, 3), id(4, 4));
const edges = [];
for (let r = 1; r < N; r++) for (let c = 0; c < N; c++) edges.push(['H', r, c, id(c, r - 1), id(c, r)]);
for (let r = 0; r < N; r++) for (let c = 1; c < N; c++) edges.push(['V', r, c, id(c - 1, r), id(c, r)]);
for (let i = edges.length - 1; i > 0; i--) { const j = Math.floor(rnd() * (i + 1)); [edges[i], edges[j]] = [edges[j], edges[i]]; }
for (const [t, r, c, a, b] of edges) if (join(a, b)) (t === 'H' ? H : V)[r][c] = false;
const START = [3, 7];
H[8][3] = false; // gate gap in the south outer wall
const open = (c, r) => {
  const o = [];
  if (r > 0 && !H[r][c]) o.push([c, r - 1]);
  if (r < N - 1 && !H[r + 1][c]) o.push([c, r + 1]);
  if (c > 0 && !V[r][c]) o.push([c - 1, r]);
  if (c < N - 1 && !V[r][c + 1]) o.push([c + 1, r]);
  return o;
};
// BFS to centre
const prev = new Map([[id(...START), null]]);
const q = [START];
let goal = null;
while (q.length) {
  const [c, r] = q.shift();
  if (c >= 3 && c <= 4 && r >= 3 && r <= 4) { goal = [c, r]; break; }
  for (const n of open(c, r)) if (!prev.has(id(...n))) { prev.set(id(...n), [c, r]); q.push(n); }
}
const path = [];
for (let p = goal; p; p = prev.get(id(...p))) path.unshift(p);
const onPath = new Set(path.map((p) => id(...p)));

const out = [];
const P = (asset, x, z, yaw = 0, scale, y = 0) => out.push({ asset, at: [+x.toFixed(3), y, +z.toFixed(3)], yaw, ...(scale ? { scale } : {}) });
const tally = {};
const add = (...a) => { P(...a); tally[a[0]] = (tally[a[0]] ?? 0) + 1; };
// ground
for (let r = 0; r < N; r++) for (let c = 0; c < N; c++) add('stone-floor', cx(c), cz(r));
// walls
for (let r = 0; r <= N; r++) for (let c = 0; c < N; c++) if (H[r][c]) add(r === 0 || r === N ? 'stone-wall' : 'hedge', cx(c), (r - 4) * 2, 0);
for (let r = 0; r < N; r++) for (let c = 0; c <= N; c++) if (V[r][c]) add(c === 0 || c === N ? 'stone-wall' : 'hedge', (c - 4) * 2, cz(r), 90);
// goal + start
add('portal', 0, 0.3, 0);
add('portal-frame', cx(3), 8, 0);
add('torch', cx(3) - 1.5, 7.65, 0); add('torch', cx(3) + 1.5, 7.65, 0);
// dead ends
const dead = [];
for (let r = 0; r < N; r++) for (let c = 0; c < N; c++) {
  if (c >= 3 && c <= 4 && r >= 3 && r <= 4) continue;
  if (open(c, r).length === 1 && !(c === 3 && r === 7 && false) && !onPath.has(id(c, r))) dead.push([c, r]);
}
// wall side of a dead end: the side opposite its opening
const pushSide = (c, r) => {
  const [oc, or] = open(c, r)[0];
  return [c - (oc - c), r - (or - r)]; // direction toward closed back wall
};
dead.sort((a, b) => Math.hypot(b[0] - 3.5, b[1] - 3.5) - Math.hypot(a[0] - 3.5, a[1] - 3.5));
dead.forEach(([c, r], i) => {
  const [bc, br] = pushSide(c, r);
  const dx = bc - c, dz = br - r;
  const x = cx(c) + dx * 0.55, z = cz(r) + dz * 0.55;
  const yaw = dz > 0 ? 180 : dz < 0 ? 0 : dx > 0 ? -90 : 90;
  if (i === 0) add('statue', x, z, yaw, 0.7);
  else if (i % 3 === 1) add('chest', x, z, yaw);
  else if (i % 3 === 2) add('bone-pile', x, z, yaw);
  else add('moss-tuft', x, z, yaw);
});
// torches at path turns, tucked in the corner of two closed sides
for (let i = 1; i < path.length - 1; i++) {
  const [c, r] = path[i];
  const a = path[i - 1], b = path[i + 1];
  if (a[0] === b[0] || a[1] === b[1]) continue;
  const sx = a[0] + b[0] - 2 * c, sz = a[1] + b[1] - 2 * r; // direction of the open corner
  add('torch', cx(c) - sx * 0.5, cz(r) - sz * 0.5, 0, 0.8);
}
// moss tufts at hedge bases (south face of horizontal hedges, inside the cell)
let m = 0;
for (let r = 1; r < N; r++) for (let c = 0; c < N; c++) if (H[r][c] && rnd() < 0.5 && m < 36) { add('moss-tuft', cx(c) + (rnd() - 0.5) * 1.2, (r - 4) * 2 + 0.42, 0, 0.9); m++; }

const f = `// GENERATED by scripts/design-labyrinth.mjs — edit the generator, not this file.
import type { Place } from '../chibi-quest.js';
export function places(): Place[] {
  return [
${out.map((p) => `    ${JSON.stringify(p)},`).join('\n')}
  ];
}
`;
writeFileSync('scenes/maps/labyrinth.ts', f);
// ASCII
let asc = '';
for (let r = 0; r <= N; r++) {
  asc += '+' + Array.from({ length: N }, (_, c) => (H[r][c] ? '--' : '  ') + '+').join('') + '\n';
  if (r < N) asc += Array.from({ length: N + 1 }, (_, c) => (V[r][c] ? '|' : ' ') + (c < N ? (onPath.has(id(c, r)) ? '()' : '  ') : '')).join('') + '\n';
}
console.log(asc, out.length, tally);
writeFileSync('docs/map-mockups/labyrinth.md', `# Labyrinth map\n\n16 m x 16 m maze, 8x8 cells of 2 m on stone-floor. Stone-wall outer ring, hedge inner walls, start gate (portal-frame, torches) south, portal goal in the centre 2x2 chamber. Path cells marked ().\n\n\`\`\`\n${asc}\`\`\`\n\nPieces: ${out.length}\n\nTally: ${JSON.stringify(tally)}\n\nNotes: dead ends hold one statue (farthest), chests, bone piles, moss; torches at path turns.\n`);
