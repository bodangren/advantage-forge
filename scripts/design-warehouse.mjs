#!/usr/bin/env node
// Warehouse map designer: 12 m x 10 m cutaway storehouse, wood floor, north and west timber walls.
// Zones: crate rows (N and mid), barrel columns (E), west double door with cart and sacks,
// clerk desk (S) with ledgers and lanterns, loft ladder corner (NE of centre).
// Writes scenes/maps/warehouse.ts and docs/map-mockups/warehouse.md.
import { writeFileSync, existsSync } from 'node:fs';

const places = [];
const dropped = new Set();
const put = (asset, x, y, z, o = {}) => {
  if (!existsSync(`out/${asset}/${asset}.glb`)) { dropped.add(asset); return; }
  const p = { asset, at: [x, y, z] };
  if (o.yaw) p.yaw = o.yaw;
  if (o.scale) p.scale = o.scale;
  places.push(p);
};
let seed = 7;
const rnd = () => { seed = (seed * 16807) % 2147483647; return seed / 2147483647 - 0.5; };

// floor: one wood-floor family, 6 x 5 tiles
for (const x of [-5, -3, -1, 1, 3, 5]) for (const z of [-4, -2, 0, 2, 4]) put('wood-floor', x, 0, z);

// walls
const NZ = -4.9, WX = -5.9;
for (const x of [-5, -3, -1, 1, 3, 5]) put('timber-wall', x, 0, NZ);
for (const z of [-4, -2, 2, 4]) put('timber-wall', WX, 0, z, { yaw: 90 });
put('double-door', WX + 0.03, 0, 0, { yaw: 90, scale: 1.1 });
const FN = NZ + 0.1, FW = WX + 0.1;

const crateStack = (x, z, n, s = 1) => {
  for (let i = 0; i < n; i++) put('crate', x + rnd() * 0.04, i * 0.41 * s, z + rnd() * 0.04, { yaw: i % 2 ? 90 + rnd() * 8 : rnd() * 8, scale: s });
};
const barrelStack = (x, z, n) => {
  for (let i = 0; i < n; i++) put('barrel', x + rnd() * 0.03, i * 0.9, z + rnd() * 0.03, { yaw: rnd() * 90 });
};

// ZONE A: crate rows along the north wall, two deep (NW)
[-5.0, -4.38, -3.76, -3.14, -2.52, -1.9].forEach((x, i) => {
  crateStack(x, -4.5, [5, 4, 5, 4, 3, 5][i]);
  crateStack(x, -3.85, [3, 4, 2, 4, 3, 2][i]);
});
// mid row of crates (aisle on both sides)
[-4.3, -3.7, -3.1, -2.5].forEach((x, i) => crateStack(x, -2.0, [3, 4, 3, 2][i]));
// ZONE B: barrel columns, east wall and mid
[-4.4, -3.45, -2.5, -1.55].forEach((z, i) => {
  barrelStack(5.35, z, [4, 3, 4, 3][i]);
  if (i < 3) barrelStack(4.4, z, [3, 2, 3][i]);
});
barrelStack(2.7, -2.0, 3);
barrelStack(3.4, -2.0, 2);
crateStack(1.6, -2.2, 4);
crateStack(0.95, -2.2, 3);
// ZONE C: west door, cart, sacks
put('handcart', -4.3, 0, 0.5, { yaw: 100 });
put('wheelbarrow', -4.6, 0, -1.2, { yaw: 80 });
[[-5.35, 1.7], [-5.1, 2.2], [-4.6, 1.9], [-5.3, 2.7]].forEach(([x, z], i) => put('sack', x, 0, z, { yaw: i * 60 }));
put('sack', -5.2, 0.4, 2.0, { yaw: 20 });
put('lantern', -5.2, 0, -0.9 - 0.5, { scale: 0.8 });
put('lantern', -5.2, 0, 1.0, { scale: 0.8 });
put('rope-coil', -3.4, 0, 1.2);
put('shelf', FW + 0.15, 0, -2.9, { yaw: 90 });
put('shelf', FW + 0.15, 0, 4.2, { yaw: 90 });
put('hay-bale', -4.8, 0, 3.9, { yaw: 10 });
// ZONE D: loft ladder corner and ledger desk
put('ladder', 0.0, 0, FN + 0.25);
put('shelf', 1.8, 0, FN + 0.17);
put('bucket', 0.9, 0, -4.4);
put('rope-coil', -0.8, 0, -4.3);
// clerk desk (S-centre)
put('desk', 1.0, 0, 3.7);
put('desk', 2.15, 0, 3.7);
put('chair', 1.6, 0, 3.0, { yaw: 0 });
put('scroll', 0.9, 0.76, 3.65, { yaw: 30 });
put('scroll', 2.2, 0.76, 3.7, { yaw: -20 });
put('candle', 1.6, 0.76, 3.75);
put('lantern', 0.0, 0, 3.0, { scale: 0.9 });
put('lantern', 3.2, 0, 3.0, { scale: 0.9 });
put('stool', 3.0, 0, 3.9);
put('bookshelf', 3.9, 0, 4.4, { yaw: 0 });
// filler rows between the door aisle (z = 0) and the desk
[-2.9, -2.3, -1.7, -1.1, -0.5].forEach((x, i) => crateStack(x, 1.5, [4, 3, 5, 3, 2][i]));
[-2.9, -2.3, -1.7].forEach((x, i) => crateStack(x, 2.15, [2, 3, 2][i]));
[0.6, 1.5, 2.4].forEach((x, i) => barrelStack(x, 1.4, [3, 2, 3][i]));
[3.6, 4.4].forEach((x, i) => barrelStack(x, 1.0, [2, 3][i]));
[3.2, 3.9, 4.6].forEach((x) => { crateStack(x, -0.6, 3); });
put('hay-bale', -0.5, 0, 3.9, { yaw: 5 });
put('sack', -1.4, 0, 3.6, { yaw: 30 });
put('sack', -1.8, 0, 3.2, { yaw: 80 });
// east: sack stacks and a spare cart
[[5.2, 0.4], [5.2, 1.0], [4.6, 0.7]].forEach(([x, z], i) => put('sack', x, 0, z, { yaw: i * 70 }));
put('sack', 5.2, 0.4, 0.7, { yaw: 40 });
put('crate', 5.3, 0, 2.3, { yaw: 5 });
put('crate', 5.3, 0.41, 2.3, { yaw: 95 });
put('crate', 5.3, 0, 3.0, { yaw: 0 });
put('barrel', 5.3, 0, 4.0);
put('barrel', 4.6, 0, 4.4, { scale: 0.9 });

writeFileSync('scenes/maps/warehouse.ts', `// GENERATED by scripts/design-warehouse.mjs — edit the generator, not this file.
import type { Place } from '../chibi-quest.js';
export function places(): Place[] {
  return [
${places.map((p) => `  { asset: '${p.asset}', at: [${p.at.map((v) => +v.toFixed(2)).join(', ')}]${p.yaw ? `, yaw: ${+p.yaw.toFixed(1)}` : ''}${p.scale ? `, scale: ${p.scale}` : ''} },`).join('\n')}
  ];
}
`);
const tally = {};
for (const p of places) tally[p.asset] = (tally[p.asset] ?? 0) + 1;
writeFileSync('docs/map-mockups/warehouse.md', `# Warehouse map (generated)

GENERATED by \`scripts/design-warehouse.mjs\`.

12 m x 10 m cutaway storehouse on wood floor, north and west timber walls.
N: tall crate rows. E: barrel columns. W: double door, cart, sacks. S: clerk desk, ledgers, lanterns.
Centre-north: loft ladder. A clear aisle runs from the door east along z = 0 and south to the desk.

| piece | count |
|---|---|
${Object.entries(tally).sort((a, b) => b[1] - a[1]).map(([k, v]) => `| ${k} | ${v} |`).join('\n')}

Total: ${places.length}
`);
console.log(`warehouse: ${places.length} places`, dropped.size ? `dropped (no glb): ${[...dropped].join(', ')}` : '');
