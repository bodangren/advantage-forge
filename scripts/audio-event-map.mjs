#!/usr/bin/env node
// Generates src/apk3d/audio/chibi-events.gen.ts from docs/sound-event-map.tsv.
// Run after editing the TSV. `--check` verifies the committed file and writes nothing.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = join(ROOT, 'docs/sound-event-map.tsv');
const TARGET = join(ROOT, 'src/apk3d/audio/chibi-events.gen.ts');

/** The mapped rows: event name to set entry (the `source` field without `chibi/`). */
function mappedEvents() {
  const lines = readFileSync(SOURCE, 'utf8').trim().split('\n');
  const events = {};
  for (const [event, source] of lines.slice(1).map((line) => line.split('\t'))) {
    if (source !== 'synth') events[event] = source.replace(/^chibi\//, '');
  }
  return events;
}

/** The generated file text. The header is a comment, so only the entries parse as rows. */
function render(events) {
  return [
    '// Generated by scripts/audio-event-map.mjs from docs/sound-event-map.tsv.',
    '// Edit the TSV, then rerun the generator. Do not edit this file by hand.',
    'export const CHIBI_EVENTS: Record<string, string> = {',
    ...Object.entries(events).map(([event, entry]) => `  ${event}: '${entry}',`),
    '};',
    '',
  ].join('\n');
}

/** Parses the entry lines of a generated file, as the wiring test does. */
function parse(text) {
  const parsed = {};
  for (const line of text.split('\n')) {
    const match = /^\s*"?([A-Za-z0-9_-]+)"?\s*:\s*["']([^"']+)["']/.exec(line);
    if (match) parsed[match[1]] = match[2];
  }
  return parsed;
}

const expected = mappedEvents();
if (process.argv.includes('--check')) {
  let actual;
  try {
    actual = parse(readFileSync(TARGET, 'utf8'));
  } catch (err) {
    console.error(`audio-event-map: cannot read ${TARGET}: ${err.message}`);
    process.exit(1);
  }
  const problems = [];
  for (const [event, entry] of Object.entries(expected)) {
    if (actual[event] !== entry)
      problems.push(`${event}: expected ${entry}, found ${actual[event] ?? 'nothing'}`);
  }
  for (const event of Object.keys(actual)) {
    if (!(event in expected)) problems.push(`${event}: not in docs/sound-event-map.tsv`);
  }
  if (problems.length) {
    for (const problem of problems) console.error(`audio-event-map: ${problem}`);
    process.exit(1);
  }
  console.log(`audio-event-map: ${Object.keys(expected).length} events current`);
} else {
  writeFileSync(TARGET, render(expected));
  console.log(`audio-event-map: ${Object.keys(expected).length} events -> ${TARGET}`);
}
