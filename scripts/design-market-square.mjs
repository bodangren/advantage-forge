#!/usr/bin/env node
// Market square map: 22 x 20 m cobbled square (11 x 10 tiles of 2 m), walled, houses on
// the north/west/east edges, fountain focal object, stall ring, edge dressing.
import { writeFileSync } from 'node:fs';
const places = [];
const put = (asset, x, z, o = {}) => {
  const p = { asset, at: [x, o.y ?? 0, z] };
  if (o.yaw) p.yaw = o.yaw;
  if (o.scale) p.scale = o.scale;
  places.push(p);
};
// ground: one cobble family
for (let c = 0; c < 11; c++) for (let r = 0; r < 10; r++) put('cobble-floor', -10 + c * 2, -9 + r * 2);
// perimeter walls (south has a gate gap handled by the wall-gate)
for (let x = -10; x <= 10; x += 2) {
  put('stone-wall', x, -9.85);
  if (Math.abs(x) > 2) put('stone-wall', x, 9.85, { yaw: 180 });
}
put('wall-gate', 0, 9.5, { yaw: 180, scale: 0.9 });
for (let z = -8; z <= 8; z += 2) { put('stone-wall', -10.85, z, { yaw: 90 }); put('stone-wall', 10.85, z, { yaw: 270 }); }
// houses (north row faces south, side rows face inward)
put('townhouse', -6.5, -7.6); put('cottage', -2.2, -8.2); put('townhouse', 2.8, -7.6); put('cottage', 7.4, -8.2);
put('cottage', -9, -3.5, { yaw: 90 }); put('townhouse', -8.6, 2.6, { yaw: 90 });
put('townhouse', 8.6, -2.6, { yaw: 270 }); put('cottage', 9, 3.4, { yaw: 270 });
put('bush', -9.2, 7.6); put('bush', 9.2, 7.6); put('bush', -4.5, -9.3); put('bush', 5.2, -9.3);
// focal fountain
put('fountain', 0, 0, { scale: 1.3 });
put('bench', -3.4, 0.2, { yaw: 90 }); put('bench', 3.4, -0.2, { yaw: 270 });
put('lantern', -2.6, -2.6); put('lantern', 2.6, 2.6); put('lantern', -2.6, 2.6); put('lantern', 2.6, -2.6);
// stall ring (each stall with its goods beside it)
const stalls = [
  ['shop-stall', -5.5, -3.4, 0, [['crate', -1.7, 0.3], ['wicker-basket', 1.7, 0.2], ['fruit-basket', 1.7, -0.5]]],
  ['market-tent', 5.4, -3.6, 0, [['barrel', -1.6, 0.2], ['sack', 1.6, 0.4], ['sack', 1.9, -0.2]]],
  ['market-tent', -5.8, 4.4, 180, [['crate', 1.6, -0.2], ['crate', 1.9, -0.2], ['fruit-basket', -1.6, 0]]],
  ['shop-stall', 5.6, 4.6, 180, [['wicker-basket', -1.8, 0], ['barrel', 1.8, 0]]],
  ['market-cart', 0, -5.2, 90, [['crate', 0, 1.1], ['pumpkin', 0.3, -1.1]]],
  ['market-cart', 0.2, 5.6, 270, [['hay-bale', 0, 1.2], ['wicker-basket', 0, -1.1]]],
];
for (const [a, x, z, yaw, goods] of stalls) {
  put(a, x, z, { yaw });
  const r = (yaw * Math.PI) / 180, c = Math.cos(r), s = Math.sin(r);
  for (const [g, dx, dz] of goods) put(g, x + dx * c + dz * s, z - dx * s + dz * c, { yaw });
}
put('well', -5.6, 0.6);
put('hay-bale', -9.3, 6.2);
// edge dressing: barrels and crates against the walls, banners and flags
for (const [x, z, a] of [[-9.4, 9, 'barrel'], [-8.6, 9, 'crate'], [9.4, 9, 'barrel'], [8.6, 9, 'crate'], [-6.2, 9.1, 'sack'], [6.2, 9.1, 'sack'], [-3.6, 9.2, 'wicker-basket'], [3.6, 9.2, 'crate']]) put(a, x, z);
for (const x of [-4.6, 4.6]) put('banner', x, 8.9, { yaw: 180 });
put('flag', -10, 9.3); put('flag', 10, 9.3); put('flag', -10, -9.3); put('flag', 10, -9.3);
put('urn', -8.5, 7.2); put('urn', 8.5, 7.2); put('urn', 3.6, -9.2); put('urn', -4.4, -9.2);
// people
put('shopkeeper', -5.5, -2.2, { yaw: 0 }); put('shopkeeper', 5.4, -2.4);
put('villager', -2, 3, { yaw: 40 }); put('villager', 2.2, -3, { yaw: 220 }); put('villager', 1.5, 8, { yaw: 180 });

const num = (v) => (Number.isInteger(v) ? String(v) : v.toFixed(2).replace(/0+$/, '').replace(/\.$/, ''));
const fmt = (p) => `  { asset: '${p.asset}', at: [${num(p.at[0])}, ${num(p.at[1])}, ${num(p.at[2])}]${p.yaw ? `, yaw: ${p.yaw}` : ''}${p.scale ? `, scale: ${p.scale}` : ''} },`;
writeFileSync('scenes/maps/market-square.ts', `// GENERATED by scripts/design-market-square.mjs — edit the generator, not this file.
import type { Place } from '../chibi-quest.js';
export function places(): Place[] {
  return [
${places.map(fmt).join('\n')}
  ];
}
`);
const tally = {};
for (const p of places) tally[p.asset] = (tally[p.asset] ?? 0) + 1;
writeFileSync('docs/map-mockups/market-square.md', `# Market square (generated by scripts/design-market-square.mjs)

22 x 20 m cobbled square (11 x 10 tiles of 2 m), stone wall ring with a south gate.
Focal fountain at the centre with benches and lanterns. Four houses on the north edge, two on each side edge.
Four stalls and two carts ring the fountain; goods stand beside each stall. Banners, flags, urns, barrels and crates dress the south wall.

| asset | count |
|---|---|
${Object.entries(tally).map(([k, v]) => `| ${k} | ${v} |`).join('\n')}

Total: ${places.length}
`);
console.log(places.length, JSON.stringify(tally));
