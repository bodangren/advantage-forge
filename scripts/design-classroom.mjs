#!/usr/bin/env node
// Chibi Sprouts week 1 classroom. Room x -6..6, z -4..4, back wall north (z=-4) and two side walls;
// the camera looks north from the open south side at child eye height. The middle floor is open for
// the compositor's children. No people, no writing. Writes scenes/maps/classroom.ts.
import { writeFileSync } from 'node:fs';

const places = [];
const put = (asset, x, z, o = {}) => {
  const p = { asset, at: [x, o.y ?? 0, z] };
  if (o.yaw) p.yaw = o.yaw;
  if (o.scale) p.scale = o.scale;
  places.push(p);
};

// Floor: 6 x 6 tiles of 2 m, z -3 to 7 (the near rows fill the lower frame)
for (let x = -5; x <= 5; x += 2) for (let z = -3; z <= 7; z += 2) put('wood-floor', x, z);

// Back wall: three rows of wall (4.5 m), a window at x -3 and x 3 in the lower row
for (const x of [-5, -3, -1, 1, 3, 5]) {
  put(x === -3 || x === 3 ? 'plaster-wall-window' : 'plaster-wall', x, -4);
  put('plaster-wall', x, -4, { y: 1.5 });
  put('plaster-wall', x, -4, { y: 3.0 });
}
// Side walls (three rows), z -3 to 5
for (const z of [-3, -1, 1, 3, 5]) {
  put('plaster-wall', -6, z, { yaw: 90 });
  put('plaster-wall', -6, z, { yaw: 90, y: 1.5 });
  put('plaster-wall', 6, z, { yaw: -90 });
  put('plaster-wall', 6, z, { yaw: -90, y: 1.5 });
  put('plaster-wall', -6, z, { yaw: 90, y: 3.0 });
  put('plaster-wall', 6, z, { yaw: -90, y: 3.0 });
}

// Back wall: bookshelves in the corners, a full bookcase between the windows.
// The bookcase spans z -0.215..0.235 around its origin, so z -3.68 puts its back
// panel at z -3.895, the same depth as the corner bookshelves.
put('bookshelf', -5.1, -3.72);
put('bookshelf', 5.1, -3.72);
put('bookcase', -1.2, -3.68);
put('basket', 1.3, -3.6, { scale: 0.9 });
put('crate', 0.6, -3.65, { scale: 0.9 });

// Left side: low table with two stools, a toy crate and a toy basket
put('table', -4.6, -1.2, { scale: 1.3 });
put('stool', -3.6, -1.7);
put('stool', -3.6, -0.7, { yaw: 180 });
put('crate', -5.5, 1.3, { yaw: 90 });
put('basket', -5.4, 2.1, { yaw: 90 });
put('basket', -5.4, 0.6, { yaw: 90, scale: 0.8 });

// Right side: cupboard on the wall, a low table with two chairs, a potted plant
put('cupboard', 5.6, -1.9, { yaw: -90 });
put('table', 4.6, 0.2, { scale: 1.3 });
put('chair', 3.7, -0.3, { yaw: 90 });
put('chair', 3.7, 0.7, { yaw: 90 });
put('pot', 5.5, 1.9, { scale: 1.4 });
put('fern', 5.5, 1.9, { y: 0.5, scale: 1.1 });
put('pot', -5.5, -3.2, { scale: 1.4 });
put('fern', -5.5, -3.2, { y: 0.5, scale: 1.1 });
put('cupboard', -5.6, 3.6, { yaw: 90 });

// The rug in the middle of the open floor
put('rug', 0, 3.0, { scale: 2 });

const num = (n) => Number(n.toFixed(2));
const lines = places.map((p) => `  { asset: '${p.asset}', at: [${p.at.map(num).join(', ')}]${p.yaw ? `, yaw: ${p.yaw}` : ''}${p.scale ? `, scale: ${p.scale}` : ''} },`);
writeFileSync('scenes/maps/classroom.ts', `// GENERATED by scripts/design-classroom.mjs — edit the generator, not this file.
import type { Place } from '../chibi-quest.js';
export function places(): Place[] {
  return [
${lines.join('\n')}
  ];
}
`);
console.log('placements', places.length);
