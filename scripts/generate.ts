async function generatedFiles(): Promise<ReadonlyMap<string, string>> {
  return new Map([
    [join(GENERATED_ROOT, 'architecture.json'), await architectureJson()],
    [join(GENERATED_ROOT, 'routes.md'), await routesMarkdown()],
    [join(GENERATED_ROOT, 'kit-catalog.md'), kitCatalogMarkdown()],
    [join(GENERATED_ROOT, 'tool-catalog.md'), toolCatalogMarkdown()],
    [
      join(GENERATED_ROOT, 'capability-catalog.md'),
      capabilityCatalogMarkdown(),
    ],
    [join(GENERATED_ROOT, 'output-contracts.md'), outputContractsMarkdown()],
  ]);
}

async function main(): Promise<void> {
  const check = process.argv.includes('--check');
  const outputs = await generatedFiles();
  const stale: string[] = [];
  for (const [path, content] of outputs) {
    if (check) {
      let current = '';
      try {
        current = await readFile(path, 'utf8');
      } catch {
        /* Missing generated files are stale. */
      }
      if (current !== content) stale.push(relative(PROJECT_ROOT, path));
    } else {
      await mkdir(dirname(path), { recursive: true });
      await writeFile(path, content, 'utf8');
    }
  }
  if (stale.length > 0) {
    console.error(`Generated facts are stale: ${stale.join(', ')}`);
    process.exitCode = 1;
  } else {
    console.log(
      check
        ? 'Generated facts are current.'
        : 'Generated architecture, route, kit, tool, capability, and output facts.',
    );
  }
}

await main();
