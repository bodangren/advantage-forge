#!/usr/bin/env node
// Boss arena: circular sand pit, one stone-wall ring, ruin-column ring, throne dais north, gate south.
// Tiles 2 m on odd centers (-9..9). Wall ring R=8.5 (27 segments of ~1.97 m), front face inward.
import { writeFileSync } from 'node:fs';
const P = [];
const r2 = (n) => Math.round(n * 100) / 100;
const add = (asset, x, z, yaw = 0, scale, y = 0) => {
  const p = { asset, at: [r2(x), y, r2(z)], yaw: Math.round(yaw) };
  if (scale) p.scale = scale;
  P.push(p);
};
const faceIn = (th) => (Math.atan2(-Math.cos(th), -Math.sin(th)) * 180) / Math.PI;
const pol = (R, th) => [R * Math.cos(th), R * Math.sin(th)];
const S = Math.PI / 2; // south angle (z+)
const N = -Math.PI / 2;

// floor: one material, sand; whole pit plus a one-tile rim that follows the circle
for (let i = -6; i <= 5; i++)
  for (let j = -6; j <= 5; j++) {
    const x = i * 2 + 1, z = j * 2 + 1;
    if (Math.hypot(x, z) > 9.6) continue;
    add('desert-ground', x, z);
  }
for (const x of [-1, 1]) add('desert-ground', x, 11); // gate approach
// raised throne dais: 3 stacked stone tiles per cell (top at y = 1.0), stairs in front
for (const x of [-2, 0, 2]) for (const t of [0.4, 0.7, 1.0]) add('stone-ground', x, -7, 0, undefined, t);
add('stairs-stone', 0, -5.2, 0);
// wall ring
const WN = 27, RW = 8.5;
const gateIdx = [], step = (2 * Math.PI) / WN;
for (let i = 0; i < WN; i++) {
  const th = S + (i - 0.5) * step; // segment i=0 and i=1 straddle the south
  const rel = i;
  if (rel === 0 || rel === 1) continue; // gate spans segments 0,1
  const [x, z] = pol(RW, th + step * 0.5 - step * 0.5);
  add('stone-wall', x, z, faceIn(th), 2);
}
// gate centered between segment 0 and 1 centres => angle S+0.0*step ... centres at S-0.5step and S+0.5step
{ const [x, z] = pol(RW + 0.1, S); add('wall-gate', x, z, 180, 0.9); }

// throne on dais
add('throne', 0, -7.5, 0, undefined, 1);
add('rug', 0, -6.3, 0, undefined, 1.02);
add('banner', -2.7, -7.2, 0, undefined, 1);
add('banner', 2.7, -7.2, 0, undefined, 1);
add('brazier', -1.6, -6.4, 0, undefined, 1);
add('brazier', 1.6, -6.4, 0, undefined, 1);
add('brazier', -2.3, -4.6, 0); add('brazier', 2.3, -4.6, 0);
// central ritual focal: circle ringed by bones and rubble
add('ritual-circle', 0, 1, 0, 2);
for (let k = 0; k < 6; k++) { const [x, z] = [3.1 * Math.cos(k * Math.PI / 3 + 0.3), 1 + 3.1 * Math.sin(k * Math.PI / 3 + 0.3)]; add(k % 2 ? 'rubble' : 'bone-pile', x, z, k * 60); }
// two fallen-pillar groups (rubble + bones)
for (const [cx, cz] of [[-4.5, -2], [4.7, 3.2]]) { add('rubble', cx, cz, 30); add('rubble', cx + 0.9, cz + 0.5, 100); add('pillar', cx - 0.6, cz + 0.8, 70); add('bone-pile', cx + 0.2, cz - 0.9, 0); }
// weapon scatter leaning on the wall
for (const th of [S + 2.5, S + 3.4, N + 1.05, S - 2.5]) {
  const [x, z] = pol(7.8, th), y = faceIn(th);
  add('gladiator-shield', x, z, y); const [x1, z1] = pol(7.7, th + 0.12); add('gladiator-sword', x1, z1, y + 90); const [x2, z2] = pol(7.8, th - 0.12); add('pike', x2, z2, y, 0.7);
}
// bones near the gate
for (const s2 of [-1, 1]) { const [x, z] = pol(7.6, S + s2 * 0.3); add('bone-pile', x, z, s2 * 50); }

// ring of broken pillars just inside the wall
const colAngles = [];
for (let k = 0; k < 16; k++) colAngles.push(N + (k + 0.5) * (2 * Math.PI / 16));
let cols = 0;
for (const th of colAngles) {
  const [x, z] = pol(7.2, th);
  if (Math.abs(x) < 4 && z < -4) continue; // throne dais
  if (Math.abs(x) < 2.6 && z > 0) continue; // gate lane
  add('pillar', x, z, faceIn(th)); cols++;
  const [bx, bz] = pol(6.6, th + 0.12);
  if (cols % 2 === 0) add('bone-pile', bx, bz, th * 57);
  else if (cols % 3 === 0) add('rubble', bx, bz, th * 57);
}
// traps flanking the gate lane, tucked at the wall
for (const s of [-1, 1]) {
  const [x, z] = pol(6.4, S + s * 0.5);
  add('spike-trap', x, z, 0);
  const [x2, z2] = pol(6.0, S + s * 0.85);
  add('bear-trap', x2, z2, s * 40);
}
// outside: braziers and 5 pike barricade clusters on the one-tile rim
for (let k = 0; k < 8; k++) { const th = S + (k + 0.5) * Math.PI / 4; const [x, z] = pol(9.3, th); add('brazier', x, z, 0); }
for (const c of [S + 0.8, S + 2.4, S + 4.0, S + 5.5, S - 0.8 + 2 * Math.PI * 0 + 0.0]) {
  if (Math.abs(c - (S - 0.8)) < 1e-9) continue;
  for (let q = 0; q < 7; q++) { const [x, z] = pol(9.4, c - 0.18 + q * 0.06); add('pike', x, z, 0, 0.5); }
}
const tally = {};
for (const p of P) tally[p.asset] = (tally[p.asset] ?? 0) + 1;
const ts = `// GENERATED by scripts/design-boss-arena.mjs — edit the generator, not this file.
import type { Place } from '../chibi-quest.js';
export function places(): Place[] { return ${JSON.stringify(P)}; }
`;
writeFileSync('scenes/maps/boss-arena.ts', ts);
const md = `# Boss arena map\n\nGenerated by scripts/design-boss-arena.mjs. ${P.length} pieces.\n\nLayout: 20 m sand disc (desert-ground), stone-wall ring R 8.5 m with a south wall-gate, 16-slot ruin-column ring inside, stone dais with throne, banners and braziers at the north, traps by the gate, braziers and pike barricades on the outer rim.\n\n## Tally\n${Object.entries(tally).map(([k, v]) => `- ${k}: ${v}`).join('\n')}\n\nMissing: weapon-rack - a weapon rack.\n`;
writeFileSync('docs/map-mockups/boss-arena.md', md);
console.log(P.length, tally);
