#!/usr/bin/env node
// Riverbank map designer: 22 x 18 m river bend, bridge, ford, fishing bench, mill cart path.
// Grid 11 x 9 tiles of 2 m. col 1..11 west->east, row 1..9 north->south.
// Cell (c,r) center: x = (c-6)*2, z = (r-5)*2. Anchor: docs/map-mockups/riverbank.jpg.
import { writeFileSync } from 'node:fs';
const X = (c) => (c - 6) * 2;
const Z = (r) => (r - 5) * 2;
const places = [];
const put = (asset, x, z, o = {}) => {
  const p = { asset, at: [x, o.y ?? 0, z] };
  if (o.yaw) p.yaw = o.yaw;
  if (o.scale) p.scale = o.scale;
  places.push(p);
};
// River: enters north at c8, runs south r1-3, bends west at (8,4), flows west on (7,4),
// bends south at (6,4), then runs south along c6 to the south edge.
const RIVER = new Map([
  ['8,1', ['river-straight', 0]], ['8,2', ['river-straight', 0]], ['8,3', ['river-straight', 0]],
  ['8,4', ['river-bend', 90]], ['7,4', ['river-straight', 90]], ['6,4', ['river-bend', 270]],
  ['6,5', ['river-straight', 0]], ['6,6', ['river-straight', 0]], ['6,7', ['river-straight', 0]],
  ['6,8', ['river-straight', 0]], ['6,9', ['river-straight', 0]],
]);
// Cart path (dirt road) along r6 west of the bridge and east of it, then north on c9? keep simple.
const ROAD = new Map();
for (const c of [1, 2, 3, 4, 5, 7, 8, 9]) ROAD.set(`${c},6`, ['dirt-road-straight', 90]);
const grid = [];
for (let r = 1; r <= 9; r++) {
  let row = '';
  for (let c = 1; c <= 11; c++) {
    const k = `${c},${r}`;
    const t = RIVER.get(k) ?? ROAD.get(k) ?? ['grass-ground', 0];
    put(t[0], X(c), Z(r), { yaw: t[1] });
    row += RIVER.has(k) ? '~' : ROAD.has(k) ? '=' : '.';
  }
  grid.push(row);
}
// landmarks
put('bridge', 0, 2, { yaw: 0 });
put('watermill', 7.4, -5.4, { yaw: 200, scale: 0.8 }); // mill on the east bank (focal)
put('hut', 8.4, -3.2, { yaw: 220, scale: 0.7 });
put('wagon', 6.2, 4.4, { yaw: 90 }); // mill cart at the roadside
put('bench', -2.4, -2.6, { yaw: 90 }); // fishing spot facing the water
put('fishing-pole', -1.9, -3.9, { yaw: 90 });
put('bucket', -2.6, -3.5);
put('rowboat', 0, 5.2, { yaw: 0, y: -0.04, scale: 0.8 });
// ford stones across the river at z=-2.6? ford sits in the E-W stretch (7,4)
for (const [x, z] of [[2.6, -2.5], [3.1, -1.7], [3.7, -2.3], [4.2, -1.4]]) put('river-rock', x, z, { y: -0.06, scale: 0.7 });
for (const [x, z] of [[-0.3, -1.2], [0.4, -2.0], [-0.2, -2.9]]) put('river-rock', x, z, { y: -0.06, scale: 0.6 });
// boulders and rock clusters
put('boulder', -8.2, 2.8, { yaw: 30 });
put('rock-cluster', 9, 6.2, { yaw: 120 });
put('rock-cluster', -4.2, -6.6, { yaw: 60 });
put('tree-stump', -6.6, -2.2, { yaw: 40 });
put('log', 4.6, 5.9, { yaw: 70 });
// fences: pasture line and gate-like fence north
for (let i = 0; i < 5; i++) put('fence', -7.5 + i * 1.5, -5.2 + (i % 2) * 0.05, { yaw: 0 });
for (let i = 0; i < 3; i++) put('fence', 3.4 + i * 1.5, 7.4, { yaw: 0 });
// willows and trees
for (const [x, z, a, yaw, s] of [
  [-6.8, -4.2, 'willow-tree', 20, 1.1], [-1.6, -6.8, 'willow-tree', 160, 1.0], [2.0, 6.6, 'willow-tree', 80, 0.9],
  [-9.2, -1.0, 'oak-tree', 50, 0.9], [-9.4, 5.6, 'oak-tree', 200, 1.0], [-5.6, 7.2, 'oak-tree', 120, 0.85],
  [3.6, -6.6, 'oak-tree', 300, 0.95], [10.2, -0.6, 'oak-tree', 15, 1.0], [10.2, 1.6, 'oak-tree', 250, 0.9],
  [-3.6, 2.8, 'oak-tree', 330, 0.75],
]) put(a, x, z, { yaw, scale: s });
// reeds along banks (c6 river west/east banks, bend, c8 banks)
const reeds = [
  [-0.95, 4.0], [0.95, 6.6], [-0.95, 7.8], [0.95, 3.4], [-0.95, 0.4], [0.95, 0.2], [-0.95, -1.3],
  [1.9, -3.5], [3.0, -0.9], [5.0, -3.3], [5.0, -6.5], [3.0, -6.0], [6.95, -1.8], [3.0, -4.9], [5.1, -7.6],
  [-2.2, -3.9], [-1.4, -4.2], [1.6, 0.9], [-1.5, 6.1],
];
for (const [x, z] of reeds) put('reeds', x, z, { yaw: Math.round((x * 37 + z * 91) % 360) });
// flowers, bushes, grass
for (const [x, z] of [[-6, 0.6], [-3, 4.4], [-7.8, 4.2], [-2.6, 0.2], [2.8, 2.6], [4.4, 1.4], [8.6, 3.2], [8, 7], [3.6, 7.2], [-8.8, -6.2], [-4.4, 3.6], [7.4, 0.8], [1.6, -5.6], [9.6, -1.4], [-5.4, 5.6], [0.8, 8.0]])
  put('wildflowers', x, z, { yaw: Math.round((x * 53 + z * 17) % 360) });
for (const [x, z] of [[-8.4, -6.8], [-4.6, -4.6], [-9.6, 3.6], [3.4, 4.2], [9.6, 4.6], [9.4, 7.6], [-3.0, 7.4], [1.4, -7.4], [5.6, -4.8], [-7.2, 6.4], [-0.6, -5.2]])
  put('bush', x, z, { yaw: Math.round((x * 29 + z * 71) % 360), scale: 0.9 });
for (const [x, z] of [[-5.2, 2.6], [-1.8, 4.6], [-8.0, -3.0], [4.0, 3.0], [8.6, 5.6], [-4.0, -1.0], [2.4, -4.4], [9.2, -5.4], [-6.4, 4.4], [2.4, 7.4], [-9.2, 0.8], [5.6, 6.8]])
  put('tall-grass', x, z, { yaw: Math.round((x * 11 + z * 7) % 360) });
for (const [x, z] of [[-2.6, 1.4], [-1.2, 3.6], [-3.4, 3.6], [-5.4, 4.6]]) put('fern', x, z, { yaw: 90 });

const header = `// GENERATED by scripts/design-riverbank.mjs — edit the generator, not this file.\nimport type { Place } from '../chibi-quest.js';\nexport function places(): Place[] {\n  return ${JSON.stringify(places)};\n}\n`;
writeFileSync('scenes/maps/riverbank.ts', header);
const tally = {};
for (const p of places) tally[p.asset] = (tally[p.asset] ?? 0) + 1;
const doc = `# Riverbank map\n\nGenerated by scripts/design-riverbank.mjs. 22 x 18 m (11 x 9 tiles). ${places.length} placements.\n\n\`\`\`\n${grid.join('\n')}\n\`\`\`\n~ river, = cart road, . grass. River enters north at col 8, bends west, then south along col 6. Bridge at (0,2), ford stones at the west-east stretch, fishing bench on the west bank, mill and hut on the east bank.\n\n## Tally\n${Object.entries(tally).map(([a, n]) => `- ${a}: ${n}`).join('\n')}\n`;
writeFileSync('docs/map-mockups/riverbank.md', doc);
console.log(grid.join('\n'));
console.log(places.length, 'placements');
