#!/usr/bin/env node
// Barracks map designer: 20 x 16 m soldier compound on dirt-ground.
// Zones: two bunk houses (north), drill yard with hay-bale targets (west/south),
// mess tent with fire (east), flagpole at the head of a cobble path (centre).
// +X east, -Z north. Tiles 2 m, centres on even metres.
import { writeFileSync } from 'node:fs';

const places = [];
const put = (asset, x, z, o = {}) => {
  const p = { asset, at: [x, o.y ?? 0, z] };
  if (o.yaw) p.yaw = o.yaw;
  if (o.scale) p.scale = o.scale;
  places.push(p);
};

// Ground: dirt everywhere, cobble path x=0 from south gate to the flag, cobble row z=-2 to both doors.
for (let x = -10; x <= 10; x += 2)
  for (let z = -8; z <= 8; z += 2) {
    const path = (x === 0 && z >= -2) || (z === -2 && Math.abs(x) <= 6);
    put(path ? 'cobble-floor' : 'dirt-ground', x, z);
  }

// North: two bunk houses (10.5 m wide, fronts face south), flag in front.
put('longhouse', -5.1, -5);
put('longhouse', 5.1, -5);
put('flag', 0, -0.8, { scale: 1.2 });
put('banner', -2.4, -1.4, { yaw: 0 });
put('banner', 2.4, -1.4, { yaw: 0 });
put('torch', -1.6, -1.6); put('torch', 1.6, -1.6);
put('bench', -5.1, -1.2); put('bench', 5.1, -1.2);
put('barrel', -9.4, -1.2); put('barrel', 9.4, -1.2, { yaw: 40 });
put('crate', -8.8, -1.0, { yaw: 15 }); put('crate', 8.8, -1.0, { yaw: 70 });
put('sack', 9.0, -1.8);

// Drill yard (west): hay-bale target rows, soldiers facing north at them.
for (const x of [-8, -5.5, -3]) {
  put('hay-bale', x, 1.6, { yaw: 90 });
  put('hay-bale', x, 1.6, { yaw: 0, y: 0.87 }); // stacked target
}
put('barrel', -6.75, 1.3); put('barrel', -4.25, 1.3);
put('guard', -8, 4.3, { yaw: 180 });
put('knight', -5.5, 4.3, { yaw: 180 });
put('guard', -3, 4.3, { yaw: 180 });
put('spear-warden', -5.5, 6.2, { yaw: 0 }); // drill sergeant faces the line
// Fence rails: south and west edges of the yard.
for (const x of [-9, -7, -5, -3]) put('fence', x, 7.5);
for (const z of [6.2, 4.2, 2.2]) put('fence', -10, z, { yaw: 90 });

// Armory shed (south-west of the path, door faces east) with stock.
put('shed', -1.8, 6.3, { yaw: 90 });
put('crate', -0.4, 7.3, { yaw: 20 }); put('crate', -0.4, 7.3, { y: 0.41, yaw: 50 });
put('barrel', -0.5, 5.4); put('anvil', 1.2, 6.6, { yaw: 270 });

// Mess zone (east): tent, fire ring, hay-bale seats, table.
put('tent', 7.5, 4.6, { yaw: 0 });
put('campfire', 4.4, 3.8, { scale: 1.3 });
put('hay-bale', 4.4, 2.4, { yaw: 0 }); put('hay-bale', 3.0, 3.8, { yaw: 90 }); put('hay-bale', 5.8, 3.8, { yaw: 90 });
put('table', 7.4, 2.4); put('stool', 6.5, 2.0); put('stool', 8.3, 2.0);
put('barrel', 9.4, 5.0); put('barrel', 9.4, 5.8, { yaw: 30 }); put('crate', 8.8, 6.9, { yaw: 25 }); put('sack', 9.4, 4.2);
put('guard', 5.9, 5.4, { yaw: 270 }); put('knight', 3.2, 2.4, { yaw: 120 });

// Gate: guard post at south entrance, guard posted.
put('guard-post', 3.2, 7.3, { scale: 0.8 });
put('guard', 1.8, 6.4, { yaw: 180 });
put('signpost', -1.6, 7.6, { yaw: 180 });

// Edge dressing.
for (const [x, z, s] of [[-10.2, -8, 1], [10.2, -8, 1.1], [-10.4, 0, 0.9], [10.4, 0.4, 1], [10.3, 8, 1], [-10.4, 8, 0.9], [6, 8.3, 0.9]])
  put('bush', x, z, { scale: s });
for (const x of [6, 8, 10]) put('fence', x, 8.3);
put('fence', 10.5, 7, { yaw: 90 });

const header = `// GENERATED by scripts/design-barracks.mjs — edit the generator, not this file.\nimport type { Place } from '../chibi-quest.js';\nexport function places(): Place[] { return [\n`;
writeFileSync('scenes/maps/barracks.ts', header + places.map((p) => '  ' + JSON.stringify(p) + ',').join('\n') + '\n]; }\n');
const tally = {};
for (const p of places) tally[p.asset] = (tally[p.asset] ?? 0) + 1;
writeFileSync('docs/map-mockups/barracks.md', `# Barracks map\n\n20 x 16 m soldier compound. North: two bunk houses. West and south: drill yard with hay-bale targets. East: mess tent and fire. Centre: cobble path to a flagpole. South gate: guard post.\n\n## Tally (${places.length})\n\n${Object.entries(tally).map(([a, n]) => `- ${a}: ${n}`).join('\n')}\n`);
console.log(places.length, 'pieces');
