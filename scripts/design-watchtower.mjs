#!/usr/bin/env node
// Watchtower map designer (P2). Writes scenes/maps/watchtower.ts and docs/map-mockups/watchtower.md.
// Grid: 10 x 10 tiles of 2 m, centers at odd meters -9..9. Tower at (0,-3). Path enters from the south (x=0).
import { writeFileSync } from 'node:fs';

const places = [];
const put = (asset, x, z, o = {}) => {
  const p = { asset, at: [x, o.y ?? 0, z] };
  if (o.yaw) p.yaw = o.yaw;
  if (o.scale) p.scale = o.scale;
  places.push(p);
};
const TX = 0, TZ = -3;

// ground: grass everywhere, narrow stone ring at the tower base, 1-tile cobble curve to the door
const PATH = new Set(['1,1', '1,3', '1,5', '-1,5', '-1,7', '-1,9', '-1,11']);
for (let x = -11; x <= 11; x += 2)
  for (let z = -11; z <= 11; z += 2) {
    const inPad = Math.abs(x) <= 1 && z >= -5 && z <= -1;
    put(inPad ? 'stone-ground' : PATH.has(`${x},${z}`) ? 'cobble-floor' : 'grass-ground', x, z);
  }

// focal tower + signal gear
put('tower', TX, TZ);
put('brazier', 2.2, -1.0, { scale: 1.2 });
put('brazier', -2.2, -1.0, { scale: 1.2 });
put('horn', 1.9, -0.9, { yaw: 30, scale: 1.4 });
put('ladder', -2.1, -3.2, { yaw: 90, scale: 1.3 });
put('flag', 0, -5.6, { scale: 1.2 });
put('lantern', 1.3, 0.1);
put('lantern', -1.3, 0.1);
put('guard', 1.2, 0.9, { yaw: 160, scale: 1.6 });
put('guard', -3.3, 2.4, { yaw: 120, scale: 1.6 });
put('signpost', -2.4, 7.4, { yaw: 160 });

// camp zone (tight, south-east)
put('campfire', 6.0, 5.2, { scale: 1.2 });
put('bench', 6.0, 6.9);
put('bench', 4.4, 5.2, { yaw: 90 });
put('bench', 7.6, 5.2, { yaw: 270 });
put('barrel', 8.2, 3.8, { yaw: 20 });
put('barrel', 8.9, 4.5, { yaw: 100 });
put('barrel', 7.4, 3.4, { yaw: 60 });
put('crate', 8.6, 7.2, { yaw: 15 });
put('crate', 8.2, 8.2, { yaw: 60, scale: 0.9 });
put('hay-bale', 4.2, 7.8, { yaw: 30 });
put('hay-bale', 5.2, 8.8, { yaw: 90 });
put('tent', 6.8, 8.8, { yaw: 200 });
put('guard', 4.9, 3.8, { yaw: 220, scale: 1.6 });
put('villager', 7.0, 6.0, { yaw: 150, scale: 1.6 });
put('horse', 3.2, 9.0, { yaw: 120, scale: 1.5 });

// west zone (tight): deer, log, stumps, rocks
put('deer', -6.0, 3.8, { yaw: 60, scale: 1.5 });
put('fallen-log', -6.6, 5.8, { yaw: 70 });
put('tree-stump', -5.0, 6.4, { yaw: 20 });
put('stump', -7.8, 7.2, { yaw: 100 });
put('rock-cluster', -7.6, 4.0, { yaw: 80 });
put('rock-cluster', -4.8, 3.4, { yaw: 200 });
put('boulder', -8.2, 5.6, { yaw: 120, scale: 0.8 });
put('wildflowers', -5.6, 5.0);
put('guard', -3.3, 1.6, { yaw: 120, scale: 1.6 });
put('torch', -4.2, 1.2);

// ruined look: broken wall and rubble around the tower base
for (const [x, z, yaw] of [[-2.9, -2.0, 80], [-3.2, -4.0, 100], [2.9, -4.4, 260], [2.7, -1.8, 280], [0.8, -6.4, 0], [-1.4, -6.4, 10]]) put('broken-wall', x, z, { yaw, scale: 0.7 });
for (const [x, z, y] of [[-2.4, -0.6, 10], [2.2, -0.2, 70], [-3.2, -5.6, 140], [3.2, -5.6, 200], [-2.6, -3.0, 30], [2.8, -3.2, 160]]) put('rock-cluster', x, z, { yaw: y, scale: 0.6 });
put('boulder', -3.6, -6.0, { yaw: 40, scale: 0.6 });
put('boulder', 3.6, -0.6, { yaw: 90, scale: 0.6 });

// stone fence: ring around the hill, gaps at the south path and the east camp
const fence = [];
for (let x = -8.1; x <= 8.2; x += 1.8) fence.push([x, -9.2, 0]); // north run
for (let z = -7.4; z <= 8.2; z += 1.8) fence.push([-9.4, z, 90]); // west run
for (let z = -7.4; z <= -1; z += 1.8) fence.push([9.4, z, 90]); // east run, north part
for (let x = -8.1; x <= -2.4; x += 1.8) fence.push([x, 9.4, 0]); // south, west of the gate
for (const [x, z, yaw] of fence) put('stone-wall', x, z, { yaw, scale: 0.8 });
put('fence', 3.0, 9.4);
put('fence', 4.8, 9.4);
put('boulder', 9.2, 0.0, { yaw: 10, scale: 0.9 });
put('boulder', -9.2, 9.0, { yaw: 70, scale: 0.8 });
put('boulder', -7.4, -1.4, { yaw: 40 });
put('boulder', 9.2, -2.0, { yaw: 40 });


// low edge trees and bushes
for (const [x, z, a, s] of [[-9.6, -9.6, 'oak-tree', 0.8], [-6, -10, 'pine-tree', 0.7], [5.5, -10, 'pine-tree', 0.7], [9.8, -9.2, 'oak-tree', 0.75],
  [-10.2, 3, 'pine-tree', 0.7], [10.2, -4, 'oak-tree', 0.7], [10, 9.6, 'oak-tree', 0.7], [-10, 9.8, 'pine-tree', 0.7]]) put(a, x, z, { yaw: (x * 53 + z * 17) % 360, scale: s });
for (const [x, z] of [[-4.6, -8.2], [4.2, -8.0], [-8.6, -5.2], [8.6, -6.0], [-3.2, 9], [8.8, 9.0], [9, -2.6], [-8.8, 3.0], [2.6, -7.8], [-2.8, -7.8]]) put('bush', x, z, { yaw: (x * 31) % 360 });

// emit
const num = (v) => (Number.isInteger(v) ? String(v) : v.toFixed(2).replace(/0+$/, '').replace(/\.$/, ''));
const fmt = (p) => `  { asset: '${p.asset}', at: [${num(p.at[0])}, ${num(p.at[1])}, ${num(p.at[2])}]${p.yaw ? `, yaw: ${p.yaw}` : ''}${p.scale ? `, scale: ${p.scale}` : ''} },`;
writeFileSync('scenes/maps/watchtower.ts', `// GENERATED by scripts/design-watchtower.mjs — edit the generator, not this file.
import type { Place } from '../chibi-quest.js';
export function places(): Place[] {
  return [
${places.map(fmt).join('\n')}
  ];
}
`);
const tally = {};
for (const p of places) tally[p.asset] = (tally[p.asset] ?? 0) + 1;
writeFileSync('docs/map-mockups/watchtower.md', `# Watchtower map (generated)

GENERATED by \`scripts/design-watchtower.mjs\`. 12x12 tiles of 2 m (24 m square), tower at (0, -3).

## Layout
Stone-ground pad (7x7 m) under the tower with two braziers, a horn and a ladder. A cobble path with lanterns
runs south to a signpost and a fence gate. Camp zone south-east: campfire, benches, barrels, crates, hay, tent,
guard, villager and horse. West zone: boulders, rocks, log, stumps and a deer. Stone wall ring on the north,
west, east and south-west edges; a few low trees and bushes at the rim.

## Tally
| piece | count |
|---|---|
${Object.entries(tally).sort((a, b) => b[1] - a[1]).map(([k, v]) => `| ${k} | ${v} |`).join('\n')}

Total: ${places.length}
`);
console.log('wrote', places.length, JSON.stringify(tally));
