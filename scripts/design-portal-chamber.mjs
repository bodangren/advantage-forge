#!/usr/bin/env node
// Portal chamber map designer. 12 m x 12 m stone chamber, x,z in [-6,6]. North (-Z) holds a
// stepped dais with the portal arch. Writes scenes/maps/portal-chamber.ts and
// docs/map-mockups/portal-chamber.md.
import { writeFileSync } from 'node:fs';

const out = [];
const put = (asset, x, z, o = {}) => {
  const p = { asset, at: [+x.toFixed(2), o.y ?? 0, +z.toFixed(2)] };
  if (o.yaw) p.yaw = o.yaw;
  if (o.scale) p.scale = o.scale;
  out.push(p);
};
let s = 7;
const rnd = () => ((s = (s * 16807) % 2147483647) / 2147483647);

// Floor: one family (stone-floor), a few cracked tiles near the south entry.
for (let x = -5; x <= 5; x += 2)
  for (let z = -5; z <= 5; z += 2) {
    const cracked = z === 5 && Math.abs(x) <= 1 || (x === -5 && z === 5) || (x === 5 && z === 3);
    put('stone-floor', x, z);
  }
// Dais: two steps of floor slabs.
for (const x of [-2, 0, 2]) for (const z of [-4, -2]) put('stone-floor', x, z, { y: 0.3 });
for (const x of [-1, 1]) put('stone-floor', x, -4, { y: 0.6 });
put('portal', 0, -4.3, { y: 0.6 });
put('magic-rune', 0, -2, { y: 0.3, scale: 1.3 });
// Low walls: two courses on the north, one elsewhere; south entry gap at x=0.
for (const x of [-4, -2, 0, 2, 4]) {
  put('wall', x, -5.8);
  if (Math.abs(x) >= 2) put('wall', x, -5.8, { y: 1.2 });
}
for (const sx of [-1, 1])
  for (const z of [-4, -2, 0, 2, 4]) {
    put('wall', sx * 5.8, z, { yaw: 90 });
    if (z <= 0 && z >= -2) put('wall', sx * 5.8, z, { yaw: 90, y: 1.2 });
  }
for (const x of [-4, -2, 2, 4]) put('wall', x, 5.8);
// Big pillars: four corners and the entry jambs.
for (const sx of [-1, 1]) for (const sz of [-1, 1]) put('pillar', sx * 5.5, sz * 5.5, { scale: 1.4 });
for (const sx of [-1, 1]) put('pillar', sx * 1.3, 5.5, { scale: 1.2 });
// Crystal pylons: obelisk plus a cluster at the foot.
for (const [x, z] of [[-3.8, -1], [3.8, -1], [-3.8, 3], [3.8, 3]]) {
  put('obelisk', x, z, { scale: 0.8 });
  put('crystal-cluster', x + 0.7, z + 0.5, { scale: 1.2 });
  put('crystal-shard', x - 0.6, z + 0.5);
}
// Braziers and sconces flank the dais.
for (const sx of [-1, 1]) {
  put('brazier', sx * 2.6, -3.2, { y: 0.3 });
  put('torch-sconce', sx * 5.3, -3);
  put('torch-sconce', sx * 5.3, 2);
}
// Candles ring the ritual circle on the dais.
for (let i = 0; i < 8; i++) {
  const a = (i / 8) * Math.PI * 2 + 0.2;
  put('candle-cluster', Math.cos(a) * 1.35, -2 + Math.sin(a) * 0.9, { y: 0.3 });
}
// Edge dressing along wall bases.
const ok = (x, z) => !(Math.abs(x) < 2.4 && z < -0.6) && !(Math.abs(x) < 1.1 && z > 4.2);
const edge = (asset, n, sc) => {
  let c = 0, tries = 0;
  while (c < n && tries++ < 600) {
    const side = Math.floor(rnd() * 4);
    const t = (rnd() - 0.5) * 9.4, d = 4.9 + rnd() * 0.3;
    const [x, z] = [[t, -d], [t, d], [-d, t], [d, t]][side];
    if (!ok(x, z) || Math.hypot(Math.abs(x) - 3.8, Math.abs(z - 1)) < 1.4) continue;
    put(asset, x, z, { yaw: Math.floor(rnd() * 4) * 90, scale: sc * (0.8 + rnd() * 0.5) });
    c++;
  }
};
edge('rubble', 22, 0.9);
edge('moss-tuft', 40, 1);
edge('rock-cluster', 6, 0.7);
edge('crystal-shard', 14, 0.9);
// Path of moss-free slabs is the bare floor: shards line the dais steps.
for (const x of [-3.4, -2.6, 2.6, 3.4]) put('crystal-shard', x, -0.7, { y: 0 });
// Fill count toward the 150 floor with candles along the entry path.
for (let i = 0; i < 10; i++) put('candle-cluster', (i % 2 ? 1 : -1) * 1.0, 4.8 - i * 0.9);
for (let i = 0; i < 10; i++) put('moss-tuft', (i % 2 ? 1 : -1) * (0.9 + rnd() * 0.3), 4.6 - i * 0.9 + 0.3);

const tally = {};
for (const p of out) tally[p.asset] = (tally[p.asset] ?? 0) + 1;
const body = out.map((p) => '  ' + JSON.stringify(p)).join(',\n');
writeFileSync('scenes/maps/portal-chamber.ts',
`// GENERATED by scripts/design-portal-chamber.mjs — edit the generator, not this file.
import type { Place } from '../chibi-quest.js';
export function places(): Place[] {
  return [
${body},
  ];
}
`);
writeFileSync('docs/map-mockups/portal-chamber.md',
`# Portal chamber map

12 m x 12 m stone chamber. Portal arch on a two-step dais at the north (focal object), ritual circle
at its foot, four obelisk pylons with crystals, big pillars at the corners and south jambs, low walls,
south entry on x=0 with a candle path to the dais.

Pieces: ${out.length}

${Object.entries(tally).map(([k, v]) => `- ${k}: ${v}`).join('\n')}
`);
console.log('pieces', out.length, tally);
