#!/usr/bin/env node
// Monastery map designer: 9 x 8 tiles of 2 m (18 m x 16 m). Writes scenes/maps/monastery.ts
// and docs/map-mockups/monastery.md from one data table.
// Cell (c,r) center: x = (c-5)*2, z = (r-4.5)*2. +X east, -Z north.
import { writeFileSync, mkdirSync } from 'node:fs';

const X = (c) => (c - 5) * 2;
const Z = (r) => (r - 4.5) * 2;
const places = [];
const put = (asset, x, z, o = {}) => {
  const p = { asset, at: [x, o.y ?? 0, z] };
  if (o.yaw) p.yaw = o.yaw;
  if (o.scale) p.scale = o.scale;
  places.push(p);
};

// --- ground: stone cloister ring, grass garden c3..7 r3..6, herb plot c1..2 r1..2, corner lawns
const glyph = Array.from({ length: 8 }, () => Array(9).fill('s'));
for (let c = 1; c <= 9; c++)
  for (let r = 1; r <= 8; r++) {
    let t = 'stone-floor', g = 's';
    const garden = c >= 3 && c <= 7 && r >= 3 && r <= 6;
    const herb = c <= 2 && r <= 2;
    const lawn = (c === 1 || c === 9) && r >= 7;
    const path = (c === 5 && r >= 3) || (r === 4 && c >= 3 && c <= 7);
    if (path) { t = 'cobble-floor'; g = '='; }
    else if (garden) { t = 'grass-ground'; g = '.'; }
    else if (herb) { t = 'grass-ground'; g = 'h'; }
    else if (lawn) { t = 'grass-ground'; g = 'o'; }
    glyph[r - 1][c - 1] = g;
    put(t, X(c), Z(r));
  }

// --- cloister arcade around the garden (x +-5, z -4..4)
for (const z of [-3, -1, 1, 3]) { put('archway', -5, z, { yaw: 90 }); put('archway', 5, z, { yaw: 90 }); }
for (const x of [-4, -2, 2, 4]) put('archway', x, 4);
for (const x of [-4, 4]) put('archway', x, -4);
for (const z of [-4, -2, 0, 2, 4]) { put('column', -5, z); put('column', 5, z); }
for (const x of [-3, 3]) { put('column', x, 4); put('column', x, -4); }
put('column', -1, 4); put('column', 1, 4);

// --- focal well on the path crossing, beds in the grass quadrants
put('well', 0, -1);
for (const [x, z] of [[-3, -3], [3, -3], [-3, 2], [3, 2]]) put('garden-bed', x, z);
for (const [x, z] of [[-3, -2.1], [3, -2.1], [-3, 3.1], [3, 3.1]]) put('garden-bed', x, z);
for (const [x, z] of [[-1.5, 2.6], [1.5, 2.6]]) put('bush', x, z, { scale: 0.8 });

// --- chapel with bell tower on the north side
put('cottage', 0, -6.2, { scale: 1.8 });
put('tower', 5.3, -6.2);
put('lantern', -1.6, -3.7);
put('lantern', 1.6, -3.7);
put('monk', 0, -3.6, { yaw: 180, scale: 1.3 });

// --- herb garden (NW)
for (const [x, z] of [[-7.5, -7], [-5.5, -7], [-7.5, -5.3], [-5.5, -5.3]]) put('garden-bed', x, z);
put('monk', -6.5, -4.4, { yaw: 20, scale: 1.3 });
put('bush', -8.4, -4.3, { scale: 0.7 });

// --- walks: benches, statue, lanterns, monks
put('bench', -6.6, -1.5, { yaw: 90 });
put('bench', -6.6, 1.5, { yaw: 90 });
put('bench', 6.6, 1.5, { yaw: 270 });
put('statue', 7.6, -1.5, { yaw: 270 });
put('lantern', -1.2, 4.6);
put('lantern', 1.2, 4.6);
put('lantern', 6.4, -3.2);
put('lantern', -6.4, 3.2);
put('monk', 0, 1.8, { yaw: 180, scale: 1.3 });
put('monk', 2.6, -1, { yaw: 270, scale: 1.3 });
put('monk', 7.2, 3.2, { yaw: 200, scale: 1.3 });
put('monk', -3.2, 5.8, { yaw: 90, scale: 1.3 });
put('monk', -6.6, 0, { yaw: 270, scale: 1.3 });

// --- corner lawns with oaks
put('oak-tree', -8, 6.6, { scale: 0.8 });
put('oak-tree', 8, 6.6, { scale: 0.8, yaw: 120 });
put('bush', -8.3, 5.2, { scale: 0.8 });
put('bush', 8.3, 5.2, { scale: 0.8 });

// --- low outer wall: south gate gap at x=-1..1, north gap behind chapel
for (const x of [-8, -6, -4, -2, 2, 4, 6, 8]) put('wall', x, 7.85);
for (const x of [-8, -6, -4, 4, 6, 8]) if (x !== 4 && x !== 6) put('wall', x, -7.85);
for (const z of [-7, -5, -3, -1, 1, 3, 5, 7]) { put('wall', -8.85, z, { yaw: 90 }); put('wall', 8.85, z, { yaw: 90 }); }

const num = (v) => (Number.isInteger(v) ? String(v) : v.toFixed(2).replace(/0+$/, '').replace(/\.$/, ''));
const fmt = (p) => `    { asset: '${p.asset}', at: [${num(p.at[0])}, ${num(p.at[1])}, ${num(p.at[2])}]${p.yaw ? `, yaw: ${p.yaw}` : ''}${p.scale ? `, scale: ${p.scale}` : ''} },`;
writeFileSync('scenes/maps/monastery.ts', `// GENERATED by scripts/design-monastery.mjs — edit the generator, not this file.
import type { Place } from '../chibi-quest.js';
export function places(): Place[] {
  return [
${places.map(fmt).join('\n')}
  ];
}
`);
const tally = {};
for (const p of places) tally[p.asset] = (tally[p.asset] ?? 0) + 1;
mkdirSync('docs/map-mockups', { recursive: true });
writeFileSync('docs/map-mockups/monastery.md', `# Monastery map (generated)

GENERATED by scripts/design-monastery.mjs. 9 x 8 tiles of 2 m (18 m x 16 m). No mockup image existed; layout inferred from the brief.

\`\`\`
${glyph.map((r) => '  ' + r.join(' ')).join('\n')}
\`\`\`
s stone cloister walk, = cobble path, . garden grass, h herb plot, o corner lawn.

Layout: arcade of archways and columns around a grass garden; the well stands where two cobble paths cross; the chapel (scaled cottage) and bell tower close the north side; the herb garden fills the NW corner; a low wall rings the court with a south gate.

## Tally (${places.length} pieces)

${Object.entries(tally).map(([k, v]) => `- ${k}: ${v}`).join('\n')}
`);
console.log(places.length, 'pieces');
console.log(glyph.map((r) => r.join(' ')).join('\n'));
