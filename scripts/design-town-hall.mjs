#!/usr/bin/env node
// Town hall map designer: 10 x 8 tiles of 2 m (20 m x 16 m). Writes scenes/maps/town-hall.ts
// and docs/map-mockups/town-hall.md. Cell (c,r): x=(c-5.5)*2, z=(r-4.5)*2. +X east, -Z north.
import { writeFileSync } from 'node:fs';

const places = [];
const put = (asset, x, z, o = {}) => {
  const p = { asset, at: [x, o.y ?? 0, z] };
  if (o.yaw) p.yaw = o.yaw;
  if (o.scale) p.scale = o.scale;
  places.push(p);
};

// --- ground: cobble plaza (hall apron, fountain square, path south) on grass ---
const plaza = (x, z) => {
  if (z <= -2 && x >= -2 && x <= 4) return true; // hall apron
  if (z >= -2 && z <= 4 && x >= -4 && x <= 6) return true; // fountain square
  if (z >= 4 && x >= -2 && x <= 2) return true; // path south
  if (z >= 0 && z <= 2 && x >= -8 && x < -4) return true; // path west to the board
  return false;
};
const rows = [];
for (let r = 1; r <= 8; r++) {
  let row = '';
  for (let c = 1; c <= 10; c++) {
    const x = (c - 5.5) * 2, z = (r - 4.5) * 2;
    const pv = plaza(x, z);
    put(pv ? 'cobble-floor' : 'grass-ground', x, z);
    row += pv ? '#' : '.';
  }
  rows.push(row);
}

// --- focal: the hall and its bell tower ---
put('townhouse', 1.2, -4.8, { scale: 1.1 });
put('tower', -3.6, -5.2, { yaw: 0 });
put('stairs-stone', 1.2, -2.2, { yaw: 0, scale: 1.3 });
put('lantern', -0.9, -2.0); put('lantern', 3.3, -2.0);
put('banner', -0.4, -2.1); put('banner', 2.8, -2.1);
put('banner', -2.0, -2.9); put('statue', 4.4, -3.0, { scale: 0.9 });
put('hedge', -0.8, -7.7, { yaw: 0 });

// --- zone 1: fountain square ---
put('fountain', 0.4, 1.2, { scale: 1.5 });
for (const [x, z, yaw] of [[-2.6, 1.2, 90], [3.4, 1.2, 270], [0.4, 3.6, 180], [-1.6, 3.2, 150], [2.4, 3.2, 210]]) put('bench', x, z, { yaw });
put('lantern', -2.0, 3.8); put('lantern', 2.8, 3.8); put('lantern', -3.4, -0.6); put('lantern', 5.0, -0.6);
put('villager', -1.2, 0.4, { yaw: 120 }); put('villager', 1.9, 0.1, { yaw: 250 }); put('villager', 0.2, 2.8, { yaw: 20 });
put('villager', 3.0, 2.2, { yaw: 220 });

// --- zone 2: notice board and speaker platform (west) ---
put('notice-board', -6.6, -1.0, { yaw: 20, scale: 1.3 });
put('notice-board', -8.2, -3.2, { yaw: 40, scale: 1.1 });
put('stairs-stone', -6.2, 1.6, { yaw: 90 }); put('stairs-stone', -5.0, 1.6, { yaw: 270 });
put('banner', -6.2, 2.7, { yaw: 180 }); put('banner', -8.2, 1.2, { yaw: 90 });
put('villager', -7.2, 0.6, { yaw: 300 }); put('villager', -5.8, -0.2, { yaw: 330 });
put('bench', -7.4, 3.4, { yaw: 0 }); put('lantern', -4.4, 2.4);
put('wildflowers', -8.6, 0.2); put('wildflowers', -4.8, -3.6); put('wildflowers', -7.6, -5.0);

// --- zone 3: market corner (east) ---
put('shop-stall', 7.6, 1.4, { yaw: 270 }); put('market-tent', 7.8, 4.0, { yaw: 250 });
put('shop-stall', 5.6, 6.0, { yaw: 180 });
for (const [a, x, z, yaw] of [['barrel', 8.8, -0.4, 0], ['barrel', 9.1, 0.3, 40], ['crate', 8.9, 2.8, 20], ['crate', 8.9, 3.4, 80], ['crate', 6.6, 2.9, 10],
  ['sack', 9.0, 5.4, 30], ['sack', 8.5, 5.9, 90], ['barrel', 7.0, 7.1, 0], ['crate', 4.2, 7.0, 15], ['sack', 6.4, 4.8, 200], ['sack', 6.8, 4.6, 120]]) put(a, x, z, { yaw });
put('villager', 6.2, 3.6, { yaw: 60 }); put('villager', 7.0, 5.2, { yaw: 160 }); put('guard', 5.4, 0.2, { yaw: 270 });
put('lantern', 5.0, 5.0); put('well', 8.6, -3.4, { yaw: 30 });

// --- south entry and edge dressing ---
put('guard', -1.4, 6.2, { yaw: 0 }); put('guard', 1.4, 6.2, { yaw: 0 });
put('lantern', -2.4, 7.2); put('lantern', 2.4, 7.2);
put('banner', -3.0, 7.4, { yaw: 180 }); put('banner', 3.0, 7.4, { yaw: 180 });
for (const x of [-9, -7, -5, -3.5]) put('fence', x, 7.6);
for (const x of [3.5, 5.3, 7.1, 9]) put('fence', x, 7.7);
for (const z of [-5, -3, -1, 1, 3, 5]) put('fence', -9.7, z, { yaw: 90 });
for (const z of [-5, -3]) put('fence', 9.7, z, { yaw: 90 });
for (const x of [5, 7, 9]) put('hedge', x, -7.6);
for (const [a, x, z, s] of [['oak-tree', -8.8, -6.2, 0.9], ['oak-tree', 6.2, -6.0, 0.9], ['oak-tree', 9.0, -1.6, 0.8], ['oak-tree', -8.8, 6.0, 0.8],
  ['bush', -8.2, -7.0, 1], ['bush', 9.0, 7.0, 1], ['bush', -6.0, 6.6, 1], ['bush', 9.2, 1.0, 0.9], ['bush', -9.2, 4.2, 0.9], ['bush', 4.4, -7.2, 1]]) put(a, x, z, { scale: s });
for (const [a, x, z] of [['rock-cluster', -5.8, 5.4], ['boulder', -9.0, 2.6], ['tall-grass', -6.4, 5.0], ['tall-grass', 4.8, 6.8], ['tall-grass', -6.0, -6.4], ['tall-grass', 9.3, 4.6],
  ['wildflowers', -4.6, 6.4], ['wildflowers', 8.6, 6.8], ['rock-cluster', 4.8, -5.8], ['wildflowers', 5.6, -4.2]]) put(a, x, z);

// --- emit ---
const num = (v) => (Number.isInteger(v) ? String(v) : String(+v.toFixed(2)));
const src = `// GENERATED by scripts/design-town-hall.mjs — edit the generator, not this file.
import type { Place } from '../chibi-quest.js';
export function places(): Place[] {
  return [
${places.map((p) => `    { asset: '${p.asset}', at: [${p.at.map(num).join(', ')}]${p.yaw ? `, yaw: ${p.yaw}` : ''}${p.scale ? `, scale: ${p.scale}` : ''} },`).join('\n')}
  ];
}
`;
writeFileSync('scenes/maps/town-hall.ts', src);
const tally = {};
for (const p of places) tally[p.asset] = (tally[p.asset] ?? 0) + 1;
writeFileSync('docs/map-mockups/town-hall.md', `# Town hall map (generated)

GENERATED by scripts/design-town-hall.mjs. 10 x 8 tiles of 2 m (20 m x 16 m). Anchor: town-hall.jpg.

\`\`\`
${rows.map((r) => '  ' + r.split('').join(' ')).join('\n')}
\`\`\`
# cobble plaza, . grass.

Layout: the timber hall and bell tower stand on the north edge. Stone steps and banners
form the front. A fountain square lies below, ringed by benches and lanterns. West: notice
boards and a stone speaker platform. East: market stalls with crates, barrels, and a well.
A cobble path leads to the south gate guards. Fences, hedges, and trees edge the map.

Pieces: ${places.length}

| asset | count |
|-------|-------|
${Object.entries(tally).sort().map(([k, v]) => `| ${k} | ${v} |`).join('\n')}
`);
console.log(places.length, 'pieces');
