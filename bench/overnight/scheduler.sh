#!/usr/bin/env bash
# Overnight scheduler: keeps up to LIMIT OpenCode trials running, at most PER trials per provider.
#
#   setsid nohup bench/overnight/scheduler.sh [limit] [per-provider] > /dev/null 2>&1 < /dev/null &
#
# The per-provider limit counts each provider/model pair (K2.8 and GLM share a plan but not a limit).
# Queue rows (bench/overnight/queue.tsv), paths relative to the repo root:
#   asset<TAB>provider/model<TAB>prompt-file<TAB>refs-dir<TAB>runs-root
# The scheduler launches the first row whose provider has a free place and removes that row.
# Running trials are marker files in bench/overnight/active/. Every finished trial appends
# "finished <asset> <model> exit=<code>" to scheduler.log. It never grafts anything.
#
# Do not edit this file in place while it runs (bash reads scripts by byte offset): write
# scheduler.sh.next and mv it over this file, then restart the scheduler.
set -u
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
repo="$(cd "$here/../.." && pwd)"
queue="$here/queue.tsv"
log="$here/scheduler.log"
act="$here/active"
limit="${1:-5}"
per="${2:-2}"
mkdir -p "$act"
touch "$queue"
echo $$ > "$here/scheduler.pid"
echo "$(date +%H:%M:%S) scheduler start limit=$limit per-provider=$per" >> "$log"

count() { find "$act" -maxdepth 1 -type f -name "$1" 2>/dev/null | wc -l; }

while true; do
  [ -f "$here/STOP" ] && { echo "$(date +%H:%M:%S) scheduler stop (STOP file)" >> "$log"; exit 0; }
  if [ "$(count '*')" -ge "$limit" ]; then sleep 15; continue; fi
  pick=0; n=0
  while IFS=$'\t' read -r asset model prompt refs root; do
    n=$((n + 1))
    [ -z "${asset:-}" ] && continue
    case "$asset" in \#*) continue ;; esac
    provider="${model%%/*}"
    mslug=$(printf '%s' "${model#*/}" | tr '.' '-' | tr -c 'A-Za-z0-9_-' '-')
    if [ "$(count "*__${provider}__${mslug}")" -lt "$per" ]; then pick=$n; break; fi
  done < "$queue"
  if [ "$pick" = 0 ]; then sleep 15; continue; fi
  row="$(sed -n "${pick}p" "$queue")"
  sed -i "${pick}d" "$queue"
  IFS=$'\t' read -r asset model prompt refs root <<< "$row"
  provider="${model%%/*}"
  slug=$(printf '%s' "${model#*/}" | tr '.' '-' | tr -c 'A-Za-z0-9_-' '-')
  tag="${asset}__${provider}__${slug}"
  touch "$act/$tag"
  echo "$(date +%H:%M:%S) launch $asset -> $model ($root)" >> "$log"
  (
    cd "$repo" || exit 1
    TRIAL_REFS="$repo/$refs" "$repo/bench/trial-one.sh" "$repo/$root/$asset" "$asset" "$repo/$prompt" "$model" >> "$log" 2>&1
    code=$?
    rm -f "$act/$tag"
    echo "$(date +%H:%M:%S) finished $asset $model exit=$code" >> "$log"
  ) > /dev/null 2>&1 < /dev/null &
  sleep 5
done
