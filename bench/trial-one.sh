#!/usr/bin/env bash
# One OpenCode trial run: a fresh workspace copy of the repo (with the forge-assets skill), the
# model works in it with `opencode run`, then the asset is rebuilt with textures and rendered.
#
#   bench/trial-one.sh <trial-dir> <asset-id> <prompt-file> <provider/model>
#
# Environment: TRIAL_REFS (a folder copied to <workspace>/reference/, e.g. concept images),
# TRIAL_RENDER_ARGS (extra args for the final render, e.g. "--az 40 --el 35"), TRIAL_TIMEOUT (s),
# TRIAL_ANIMATE=1 (also make every clip's review strip and GIF in the final build),
# TRIAL_RESUMES (default 3), TRIAL_RESUME_ONLY=1 (resume an existing run, then build again).
#
# After a crash or restart, check `opencode api GET /api/session/status`-style activity in
# ~/.local/share/opencode/log and interrupt trial sessions: `opencode api session.interrupt
# --param sessionID=<id>`. The service resumes open sessions when it starts.
#
# Do not edit this file in place while trials run: bash reads it again by byte offset after each
# command. Write a new file and rename it over this one.
set -uo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/env.sh"
TRIAL="${1:?}"; ASSET="${2:?}"; PROMPT="${3:?}"; MODEL="${4:?}"
mkdir -p "$TRIAL"; TRIAL=$(realpath "$TRIAL"); PROMPT=$(realpath "$PROMPT")
[ -n "${TRIAL_REFS:-}" ] && TRIAL_REFS=$(realpath "$TRIAL_REFS")
slug=$(printf '%s' "${MODEL#*/}" | tr '.' '-' | tr -c 'A-Za-z0-9_-' '-')
dir="$TRIAL/$slug"
ws="$dir/ws"
limit="${TRIAL_TIMEOUT:-3600}"

agent() { # <timeout-seconds> <opencode run args...>; appends to the transcript
  local t="$1"; shift
  (cd "$ws" && FORGE_VITE_CACHE="$ws/.vite-cache" FORGE_WORKERS=1 timeout "$t" \
    opencode run --standalone --auto --format json -m "$MODEL" "$@" \
    >> "$dir/transcript.jsonl" 2>> "$dir/opencode.stderr")
}

if [ "${TRIAL_RESUME_ONLY:-0}" = 1 ]; then
  [ -f "$dir/meta.json" ] || { echo "no run to resume in $dir" >&2; exit 2; }
  read -r prev_seconds code resumes < <(node -e 'const m=require(process.argv[1]); console.log(m.seconds, m.exit_code, m.resumes ?? 0)' "$dir/meta.json")
  start=$(( $(date +%s) - prev_seconds ))
else
  rm -rf "$dir"
  mkdir -p "$dir"
  # Workspace: the model-visible repo, the skill, its own git root, shared read-only dependencies.
  "$TSX" -e "import { copyRepo } from '$BENCH/lib.ts'; copyRepo('$ws');"
  mkdir -p "$ws/.claude/skills"
  cp -r "$REPO/.claude/skills/forge-assets" "$ws/.claude/skills/"
  rm -f "$ws/assets/$ASSET.ts"
  [ -n "${TRIAL_REFS:-}" ] && cp -r "$TRIAL_REFS" "$ws/reference"
  ln -s "$REPO/node_modules" "$ws/node_modules"
  (cd "$ws" && git init -q && git add -A >/dev/null 2>&1 && git -c user.email=t@t -c user.name=trial commit -qm base >/dev/null 2>&1)

  start=$(date +%s)
  echo "{\"model\":\"$MODEL\",\"started\":\"$(date -u +%FT%TZ)\"}" > "$dir/meta.json"
  : > "$dir/transcript.jsonl"
  : > "$dir/opencode.stderr"
  agent "$limit" --title "forge-trial $ASSET $slug" "$(cat "$PROMPT")"
  code=$?
  resumes=0
fi

# A dropped provider connection can end `opencode run` in the middle of the work (exit 1, and the
# transcript does not end with the model's final message). Resume the same session with the time
# that is left. A run that ends with a final message is done, whatever the exit code.
ended_with_message() {
  node -e 'let last=null; for (const l of require("fs").readFileSync(process.argv[1],"utf8").split("\n")) { try { const e=JSON.parse(l); if (e.type!=="harness") last=e; } catch {} } process.exit(last && last.type==="text" ? 0 : 1)' "$dir/transcript.jsonl"
}
session_id() { grep -o '"sessionID":"[^"]*"' "$dir/transcript.jsonl" | head -1 | cut -d'"' -f4; }
while [ "$code" != 0 ] && [ "$code" != 124 ] && [ "$resumes" -lt "${TRIAL_RESUMES:-3}" ] && ! ended_with_message; do
  left=$(( limit - ($(date +%s) - start) ))
  [ "$left" -gt 120 ] || break
  sid=$(session_id)
  [ -n "$sid" ] || break
  resumes=$((resumes + 1))
  echo "{\"type\":\"harness\",\"timestamp\":$(( $(date +%s) * 1000 )),\"resume\":$resumes,\"seconds_left\":$left}" >> "$dir/transcript.jsonl"
  agent "$left" --session "$sid" "The connection to the model provider dropped. Continue the task from where you stopped."
  code=$?
done
seconds=$(( $(date +%s) - start ))

# Keep the whole session (messages, costs, tokens) with the run. The OpenCode background service
# resumes sessions that a killed `opencode run` left open (after a timeout, or when the machine
# restarts), outside this harness and its time limit. So delete a session that did not end with
# the model's final message, after the export.
sid=$(session_id)
if [ -n "$sid" ]; then
  timeout 120 opencode session export "$sid" > "$dir/session.json" 2> /dev/null || rm -f "$dir/session.json"
  if ! ended_with_message && [ -s "$dir/session.json" ]; then
    timeout 60 opencode session delete "$sid" > /dev/null 2>&1 &&
      echo "{\"type\":\"harness\",\"timestamp\":$(( $(date +%s) * 1000 )),\"deleted_session\":\"$sid\"}" >> "$dir/transcript.jsonl"
  fi
fi

# Final, identical build for every model: inspection, sprites, then the textured turnaround last,
# so out/<asset>/ ends with the textured GLB, stats, and render.
final=1
if [ -f "$ws/assets/$ASSET.ts" ]; then
  # shellcheck disable=SC2086
  (cd "$ws" && export FORGE_VITE_CACHE="$ws/.vite-cache" &&
    timeout 600 ./forge inspect "$ASSET" --fast > "$dir/final-inspect.log" 2>&1 &&
    timeout 600 ./forge sprites "$ASSET" --fast > "$dir/final-sprites.log" 2>&1 &&
    { [ "${TRIAL_ANIMATE:-0}" != 1 ] || timeout 600 ./forge animate "$ASSET" --fast > "$dir/final-animate.log" 2>&1; } &&
    timeout 900 ./forge render "$ASSET" --no-ref ${TRIAL_RENDER_ARGS:-} > "$dir/final-render.log" 2>&1) && final=0
fi
node -e 'const fs=require("fs"); const f=process.argv[1]; const m=JSON.parse(fs.readFileSync(f)); Object.assign(m,{exit_code:Number(process.argv[2]),seconds:Number(process.argv[3]),final_build_ok:process.argv[4]==="0",asset_file:fs.existsSync(process.argv[5]),resumes:Number(process.argv[6])}); fs.writeFileSync(f, JSON.stringify(m,null,2));' \
  "$dir/meta.json" "$code" "$seconds" "$final" "$ws/assets/$ASSET.ts" "$resumes"
echo "done $MODEL: exit $code, ${seconds}s, $resumes resumes, final build $([ $final = 0 ] && echo ok || echo FAILED)"
